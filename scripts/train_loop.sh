# ---- benchmark, overlapped with the next generation (plan 047 item 0) -------
# The loop is gateless, so nothing downstream reads gen G's benchmark: gen G is
# the generator the moment it is trained. Its eval is therefore submitted to
# the hub in the background and runs alongside gen G+1's games on the same
# workers and sidecar (the hub shares streams round-robin between running
# jobs, and the eval's candidate *is* the generator, so their requests batch
# together on the canvas). eval_finish waits for it at the end of the next
# generate phase, before the sidecar makes way for the trainer. A STOP or a
# crash loses the in-flight eval with the hub; the next launch resubmits it,
# because only eval_finish writes .evaluated.
EVAL_PENDING_G=""
EVAL_JOBS=()   # "pid name dir" per job of the pending generation's eval
EVAL_T0=0
# eval_job NAME DIR LABEL [job eval args...]: one eval job in the background, writing DIR/report.json
# (and eval.games.jsonl, eval.log). A DIR that already has its report is skipped, so a relaunch
# resubmits only what the crash lost.
eval_job() {
    local name="$1" dir="$2" label="$3"; shift 3
    [ -s "$dir/report.json" ] && return 0
    mkdir -p "$dir"
    # Plan 069 item 5: the games of an interrupted benchmark are kept (`--resume`) when it is
    # submitted again with the same arguments; anything else starts the per-game file over.
    local args="$label $EVALUATOR $EVAL_MCTS_ITERS $EVAL_GAMES $EVAL_BOT_CONFIG $EVAL_BUDGET_MODE $*"
    if [ "$(cat "$dir/eval.args" 2>/dev/null)" != "$args" ]; then
        rm -f "$dir/eval.games.jsonl"
        echo "$args" > "$dir/eval.args"
    fi
    # `env`, not with_budget: a backgrounded function is a subshell, and the client must be this
    # shell's own child — it stops when its parent goes, instead of resubmitting into a later run.
    # shellcheck disable=SC2086,SC2046
    env ${EVAL_BUDGET_MODE:+BLOOD_MCTS_BUDGET=$EVAL_BUDGET_MODE} "$HUB" job eval --hub "$HUB_URL" --token-file "$HUB_TOKEN_FILE" \
            --label "$label" --priority "$BENCH_PRIORITY" --evaluator "$EVALUATOR" --mcts-iters "$EVAL_MCTS_ITERS" --games "$EVAL_GAMES" \
            ${EVAL_BOT_CONFIG:+--bot-config "$EVAL_BOT_CONFIG" --vs-config "$EVAL_BOT_CONFIG"} \
            "$@" --per-game-out "$dir/eval.games.jsonl" --out "$dir/report.json" --resume $(job_wait_args) \
            --wait >> "$dir/eval.log" 2>&1 &
    EVAL_JOBS+=("$! $name $dir")
}
# genNN for the loop's own and the anchor's nets, else the file stem: what we call a net.
net_name() { basename "$1" .onnx | sed -E 's/^(bbnet|anchor)_.*_(gen[0-9]+)$/\2/'; }
# The net gen $1 is benchmarked against: DRIVE_REF, or with DRIVE_REF=parent the net that generated
# it (the previous generation's, gen01's being INIT_CHAMPION).
drive_ref_of() {
    if [ "$DRIVE_REF" != parent ]; then echo "$DRIVE_REF"
    elif [ "$1" -le 1 ]; then echo "$INIT_CHAMPION"
    else echo "$MODEL_DIR/bbnet_${TIER}_$(printf 'gen%02d' $(($1 - 1))).onnx"; fi
}
# Plan 071 R4: the model files gen $1 plays on the ladder (DRIVE_LADDER), one per line. A fixed
# entry is itself; `geo` is the run's own gens 1, 2, 4, 8, ... below $1 whose model exists (the
# parent left out under DRIVE_REF=parent), cut to the DRIVE_LADDER_ANCHORS nearest the parent in
# the run's pooled Elo fit (`elo_fit.py --nearest`; newest first while unrated, or if the fit
# fails). A relaunch recomputes the choice, but a sub that has its report is never replayed.
# A ladder sub's name: genNN for the run's own nets, the file stem for any other (a foreign
# `bbnet_<tier>_gen58` must not read as this run's gen58).
ladder_name() {
    local stem; stem=$(basename "$1" .onnx)
    case "$stem" in "bbnet_${TIER}_gen"*) echo "${stem#bbnet_"${TIER}"_}" ;; *) echo "$stem" ;; esac
}
ladder_refs() {
    local G="$1" f k among="" picked
    for f in ${DRIVE_LADDER//,/ }; do
        if [ "$f" != geo ]; then echo "$f"; continue; fi
        for ((k = 1; k < G; k *= 2)); do
            [ "$DRIVE_REF" = parent ] && [ "$k" -eq $((G - 1)) ] && continue
            [ -f "$MODEL_DIR/bbnet_${TIER}_$(printf 'gen%02d' "$k").onnx" ] && among="$among $(printf 'gen%02d' "$k")"
        done
        [ -n "$among" ] || continue
        picked=$("$PY" "$REPO/scripts/elo_fit.py" "$RUN_DIR" --anchor "$ELO_ANCHOR" \
            --nearest "$(printf 'gen%02d' $((G - 1)))" --among "$among" --k "$DRIVE_LADDER_ANCHORS" 2>> "$LOG") \
            || picked=$(echo "$among" | tr ' ' '\n' | grep . | sort -r | head -n "$DRIVE_LADDER_ANCHORS")
        for k in $picked; do echo "$MODEL_DIR/bbnet_${TIER}_$k.onnx"; done
    done
}
eval_submit() {
    local G="$1" GG GEN_DIR MODEL RUNG_ARGS RUNG_DESC PG
    GG=$(printf 'gen%02d' "$G"); GEN_DIR="$RUN_DIR/$GG"; MODEL="$MODEL_DIR/bbnet_${TIER}_$GG"
    PG=$(printf 'gen%02d' $((G - 1)))
    EVAL_JOBS=()
    ensure_ts "$MODEL.onnx"
    if [ "$EVAL_VENUE" = drives ]; then
        REF=$(drive_ref_of "$G")
        ensure_ts "$REF" "$ORIGIN_REF"
        [ "$P1_GAMES" -gt 0 ] && ensure_ts "$MODEL_DIR/bbnet_${TIER}_$PG.onnx" "$(drive_ref_of $((G - 1)))"
        eval_job drives "$GEN_DIR/drives" "$GG drives vs $(net_name "$REF")" \
            --model "$MODEL.onnx" --seed 0 --skip-fixed-rungs \
            --positions "$DRIVE_POSITIONS" $([ "$DRIVE_SPRT" = none ] || echo "--sprt $DRIVE_SPRT") --vs-games "$DRIVE_CAP" \
            ${DRIVE_GATE:+--drive-gate "$DRIVE_GATE"} \
            --vs-evaluator "$EVALUATOR" --vs-model "$REF"
        if [ "$ORIGIN_EVERY" -gt 0 ] && [ $((G % ORIGIN_EVERY)) -eq 0 ]; then
            eval_job origin "$GEN_DIR/drives_origin" "$GG drives vs $(net_name "$ORIGIN_REF") (origin)" \
                --model "$MODEL.onnx" --seed 0 --skip-fixed-rungs \
                --positions "$DRIVE_POSITIONS" --vs-games "$ORIGIN_DRIVES" \
                --vs-evaluator "$EVALUATOR" --vs-model "$ORIGIN_REF"
        fi
        # Plan 071 R4: the ladder, at fixed pairs.
        if [ -n "$DRIVE_LADDER" ] && [ $((G % DRIVE_LADDER_EVERY)) -eq 0 ]; then
            local LREF
            for LREF in $(ladder_refs "$G"); do
                ensure_ts "$LREF"
                eval_job "ladder_$(ladder_name "$LREF")" "$GEN_DIR/drives_ladder_$(ladder_name "$LREF")" \
                    "$GG drives vs $(ladder_name "$LREF") (ladder)" \
                    --model "$MODEL.onnx" --seed 0 --skip-fixed-rungs \
                    --positions "$DRIVE_POSITIONS" --vs-games "$DRIVE_LADDER_DRIVES" \
                    --vs-evaluator "$EVALUATOR" --vs-model "$LREF"
            done
        fi
        # P1: the previous generation's drive H1, on full games against the same reference.
        if [ "$P1_GAMES" -gt 0 ] && [ -e "$RUN_DIR/$PG/.confirm" ]; then
            # shellcheck disable=SC2046
            eval_job p1 "$RUN_DIR/$PG/p1" "$PG full games vs $(net_name "$(drive_ref_of $((G - 1)))") (P1)" \
                --model "$MODEL_DIR/bbnet_${TIER}_$PG.onnx" --seed 0 --skip-fixed-rungs $(size_eval_args) \
                --sprt "$DRIVE_SPRT" --vs-games "$P1_GAMES" \
                --vs-evaluator "$EVALUATOR" --vs-model "$(drive_ref_of $((G - 1)))"
        fi
    fi
    if [ "$EVAL_VENUE" = games ] || { [ "$ANCHOR_EVERY" -gt 0 ] && [ $((G % ANCHOR_EVERY)) -eq 0 ]; }; then
        # No fixed rungs -> --skip-fixed-rungs, which keeps only the --vs rung
        # (the anchor). Passing `--rungs ""` would also work, but the dedicated
        # flag says the intent out loud.
        if [ -n "$EVAL_RUNGS" ]; then
            RUNG_ARGS="--rungs $EVAL_RUNGS"
            RUNG_DESC="$EVAL_GAMES games/rung ($EVAL_RUNGS) + "
        else
            RUNG_ARGS="--skip-fixed-rungs"
            RUNG_DESC=""
        fi
        ensure_ts "$ANCHOR"
        # shellcheck disable=SC2046,SC2086
        eval_job anchor "$GEN_DIR" "$GG full games vs $(net_name "$ANCHOR") (anchor)" \
            --model "$MODEL.onnx" --seed 0 $RUNG_ARGS $(size_eval_args) \
            --vs-games "$ANCHOR_GAMES" --vs-evaluator "$EVALUATOR" --vs-model "$ANCHOR"
    fi
    status "$GG eval submitted: $(for j in "${EVAL_JOBS[@]}"; do set -- $j; echo "$2"; done | paste -sd' ')${RUNG_DESC:+ ($RUNG_DESC)}, alongside the next generation on the hub"
    EVAL_PENDING_G="$G"
    EVAL_T0=$(date +%s)
}
# Wait for the in-flight eval jobs, if any, then report them. Needs games to run on:
# if this box's worker is not up (a resume that skipped generation, or the
# last generation), it starts the sidecar and worker for the wait and stops
# them after.
eval_finish() {
    [ -n "$EVAL_PENDING_G" ] || return 0
    local G="$EVAL_PENDING_G" GG GEN_DIR started="" j pid name dir alive=""
    GG=$(printf 'gen%02d' "$G"); GEN_DIR="$RUN_DIR/$GG"
    for j in "${EVAL_JOBS[@]}"; do read -r pid _ _ <<< "$j"; kill -0 "$pid" 2>/dev/null && alive=1; done
    if [ -n "$alive" ]; then
        if [ -z "$WORKER_PID" ]; then
            ensure_ts "$(champion)"
            nn_server_start "$(champion)"
            worker_start "$EVAL_PARALLEL_GAMES" "$GEN_DIR/eval.worker.log"
            started=1
        fi
        status "$GG eval still running $((($(date +%s) - EVAL_T0) / 60)) min in; waiting for it"
    fi
    local rc
    for j in "${EVAL_JOBS[@]}"; do
        read -r pid name dir <<< "$j"
        wait "$pid"; rc=$?
        if [ "$rc" -ne 0 ]; then
            [ -n "$started" ] && { worker_stop; nn_server_stop; }
            [ "$rc" -eq 75 ] && resumable_exit "$GG $name eval" "its games so far are in $dir/eval.games.jsonl"
            die "$GG $name eval failed — see $dir/eval.log and hub.log"
        fi
    done
    [ -n "$started" ] && { worker_stop; nn_server_stop; backend_check "$GEN_DIR/eval.worker.log" "$GG eval (local worker)"; }
    EVAL_PENDING_G=""
    EVAL_JOBS=()
    touch "$GEN_DIR/.evaluated"
    eval_report "$G" "$((($(date +%s) - EVAL_T0) / 60))"
}
# The verdict and curve lines for an evaluated generation. A persisted verdict
# is final (gated era: PROMOTED/REJECTED; gateless: BENCHMARKED). Re-deriving
# it on resume would replay the whole promotion history over champion.txt —
# and clobber a champion set by hand (plan 032 #7c installed Q7 that way; the
# first relaunch silently reverted it to gen03 and generated gen08 from the
# wrong net).
eval_report() {
    local G="$1" MINUTES="$2" GG GEN_DIR PG SUMMARY_LINE CURVE BL PB
    GG=$(printf 'gen%02d' "$G"); GEN_DIR="$RUN_DIR/$GG"
    PG=$(printf 'gen%02d' $((G - 1)))
    [ -f "$GEN_DIR/verdict" ] && return 0
    echo "BENCHMARKED" > "$GEN_DIR/verdict"
    # Plan 051: the drive match against the reference, and the previous generation's P1.
    if [ -s "$GEN_DIR/drives/report.json" ]; then
        status "$GG drives done (${MINUTES} min, overlapped): $("$PY" "$SUMMARY" "$GEN_DIR/drives/report.json")"
        status "$GG drives vs $(net_name "$(drive_ref_of "$G")"): $("$PY" "$REPO/scripts/drive_curve.py" "$RUN_DIR" | paste -sd'|')"
        if [ "$P1_GAMES" -gt 0 ] && grep -q '"verdict": *"H1"' "$GEN_DIR/drives/report.json"; then
            touch "$GEN_DIR/.confirm"
            status "$GG drive H1 against $(net_name "$DRIVE_REF"): P1 confirmation on full games follows with the next generation"
        fi
    fi
    if [ -s "$GEN_DIR/drives_origin/report.json" ]; then
        status "$GG vs origin $(net_name "$ORIGIN_REF"): $("$PY" "$REPO/scripts/drive_curve.py" "$RUN_DIR" --sub drives_origin | paste -sd'|')"
    fi
    # Plan 071 R4: the ladder's matches, then the Elo fit over every drive sub of the run.
    if [ -n "$DRIVE_LADDER" ]; then
        local LD
        for LD in "$GEN_DIR"/drives_ladder_*; do
            [ -s "$LD/report.json" ] || continue
            status "$GG ladder vs ${LD##*/drives_ladder_}: $("$PY" "$SUMMARY" "$LD/report.json")"
        done
        status "$GG elo: $("$PY" "$REPO/scripts/elo_fit.py" "$RUN_DIR" --anchor "$ELO_ANCHOR" --summary "$GG" \
            --json "$RUN_DIR/elo.json" --csv "$RUN_DIR/elo.csv" --png "$RUN_DIR/elo.png" 2>> "$LOG" || echo "elo_fit.py failed (see $LOG)")"
    fi
    if [ -s "$RUN_DIR/$PG/p1/report.json" ] && [ ! -e "$RUN_DIR/$PG/.p1_reported" ]; then
        status "$PG P1 vs $(net_name "$DRIVE_REF"): $("$PY" "$REPO/scripts/drive_curve.py" "$RUN_DIR" --sub p1 | paste -sd'|')"
        touch "$RUN_DIR/$PG/.p1_reported"
    fi
    [ -s "$GEN_DIR/report.json" ] || return 0
    SUMMARY_LINE=$("$PY" "$SUMMARY" "$GEN_DIR/report.json")
    status "$GG eval done (${MINUTES} min, overlapped): $SUMMARY_LINE"
    # The curve is what the benchmark is for: this generation's point, the
    # 3-gen rolling mean, and the advisory flags — all against the same
    # frozen opponent, so successive lines are directly comparable.
    # shellcheck disable=SC2046
    CURVE=$("$PY" "$REPO/scripts/anchor_curve.py" "$RUN_DIR" --anchor "$(basename "$ANCHOR")" --summary "$G" $(size_curve_args) 2>&1) \
        || CURVE="anchor_curve.py failed: $CURVE"
    status "$GG curve: $CURVE"
    # Plan 042: the other boards' anchor points, one line each, so a size
    # that lags is visible next to the pooled curve.
    if [ "$SIZE_MODE" != fixed ]; then
        for B in $(echo "$EVAL_BOARD_SIZES" | tr ',' ' '); do
            BL=$(grep -o "\"board\": *\"$B/[0-9]*\"" "$GEN_DIR/report.json" | head -1 | sed 's/.*"\([^"]*\)"$/\1/')
            [ -n "$BL" ] && [ "$BL" != "$ANCHOR_BOARD" ] || continue
            PB=$("$PY" "$REPO/scripts/anchor_curve.py" "$RUN_DIR" --anchor "$(basename "$ANCHOR")" --summary "$G" --board "$BL" 2>&1) || continue
            status "$GG curve: $PB"
        done
    fi
    case "$CURVE" in
        *REGRESSION*|*PLATEAU*) status "ALERT $GG: $(echo "$CURVE" | grep -o '\(REGRESSION\|PLATEAU\)[^|]*' | tr '\n' ' ')— advisory (plan 030): inspect, and roll back champion.txt by hand if warranted" ;;
    esac
}

# ---- generation loop ----------------------------------------------------------
G=1
while [ "$G" -le "$MAX_GENS" ]; do
    GG=$(printf 'gen%02d' "$G")
    GEN_DIR="$RUN_DIR/$GG"
    MODEL="$MODEL_DIR/bbnet_${TIER}_$GG"
    mkdir -p "$GEN_DIR"

    # -- 1. generate ----------------------------------------------------------
    check_stop "before $GG generate"
    if [ ! -e "$GEN_DIR/.generated" ]; then
        SECONDS=0
        CHAMP="$(champion)"
        ensure_ts "$CHAMP"
        nn_server_start "$CHAMP" "$GEN_SIDECARS"
        # Plan 041: the games run on whatever workers are connected to the
        # hub — this box's local worker (started here, inside the sidecar's
        # lifetime, with GEN_PARALLEL_GAMES streams) plus any remote ones,
        # which use tract. One job writes all 8 shards; shard K's seeds are
        # SEED_BASE + G*1e6 + K*1e5 + g, exactly the per-shard layout the
        # `botbowl-ui dataset` processes used, and --heuristic-shards keeps
        # the hedge shards on the heuristic evaluator. `--nn-server` on the
        # worker is harmless if the server never came up (it falls back to
        # tract and warns once, in generate.worker.log).
        GEN_LABELS=0
        [ -n "$(stream_label_args "$TRAIN_SHARDS $VAL_SHARDS")" ] && GEN_LABELS="$LABEL_STREAMS"
        worker_start "$GEN_PARALLEL_GAMES" "$GEN_DIR/generate.worker.log" "$GEN_LABELS"
        SIZE_ARGS=$(size_gen_args)
        status "$GG generate${EXPLORE_ARGS:+ (explore: $EXPLORE_ARGS)}$([ "$GEN_LABELS" -gt 0 ] && echo " with streamed MC labels ($MC_LABEL_PLAYOUTS playouts, +$LABEL_STREAMS label streams)"): 8x$GAMES_PER_SHARD games ($EVALUATOR: $(basename "$CHAMP")${NN_SERVER_PID:+ via sidecar}${HEUR_SHARDS:+ + heuristic hedge}), local x$GEN_PARALLEL_GAMES$([ "${#NN_EXTRA[@]}" -gt 0 ] && echo " over $((${#NN_EXTRA[@]} + 1)) sidecars")$([ "$NN_BACKEND" = inproc ] && echo " in-process") + hub workers, disk free $(free_gb)${SIZE_ARGS:+, sizes: $(echo "$SIZE_ARGS" | tr -s ' \\\n' ' ')}"
        # Plan 069 item 5: shards already here are an interrupted phase's; the job resumes them.
        if [ "$GEN_RESUME" = on ] && ls "$GEN_DIR"/shard*.jsonl > /dev/null 2>&1; then
            status "$GG generate resumes: $(gen_progress "$GEN_DIR" $((GAMES_PER_SHARD * 8)))"
        fi
        generate_jobs "$GEN_DIR" "$CHAMP" "$SIZE_ARGS"; GEN_RC=$?
        if [ "$GEN_RC" -ne 0 ]; then
            worker_stop
            nn_server_stop
            [ "$GEN_RC" -eq 75 ] && resumable_exit "$GG generate" "$(gen_progress "$GEN_DIR" $((GAMES_PER_SHARD * 8)))"
            die "$GG generate failed — see generate.log, hub.log and generate.worker.log"
        fi
        # A local worker that silently ran on tract all generation is the
        # failure this phase can otherwise hide: it finishes, its corpus is
        # correct, and it is just 4x slower. Surface it.
        case "$EVALUATOR" in nn|nn-value) backend_check "$GEN_DIR/generate.worker.log" "$GG generate (local worker)" ;; esac
        GEN_MIN=$((SECONDS / 60))
        # The previous generation's eval shared these workers; it must be
        # done before the sidecar makes way for the trainer.
        eval_finish
        worker_stop
        # The trainer needs the whole card; never let the two contend.
        nn_server_stop
        GAMES=0
        for K in $NN_SHARDS $HEUR_SHARDS; do
            [ -s "$GEN_DIR/shard$K.jsonl" ] || die "$GG shard$K.jsonl empty/missing — see generate.log"
            GAMES=$((GAMES + $(wc -l < "$GEN_DIR/shard$K.jsonl")))
        done
        status "$GG generate done ($GEN_MIN min$([ "$GEN_LABELS" -gt 0 ] && echo ", labels streamed")): $(gen_progress "$GEN_DIR" $((GAMES_PER_SHARD * 8)))"
        # Plan 069 item 4b: the streamed labels' summary lines, where the mc-label phase counts the
        # unlabelled trajectories from (once: this block runs once per generation).
        if [ "$GEN_LABELS" -gt 0 ]; then
            # The last summary line per output (a resumed phase's log holds its earlier attempts).
            grep -h '^mc-label: ' "$GEN_DIR"/generate.log | awk '{a[$4] = $0} END {for (k in a) print a[k]}' >> "$GEN_DIR/mc_label.log" 2>/dev/null
            grep -h 'WARN: streamed labels' "$GEN_DIR"/generate.log | while read -r l; do status "WARN: $GG $l (the mc-label phase labels what is missing)"; done
        fi
        # What the corpus actually contains, not just how much of it there is.
        # A drive that ends without a touchdown ran out of half, so this is
        # the share the bots converted — the generation-side twin of the TD/g
        # the eval phase prints. A loop that is learning to stall rather than
        # to score shows it here first, while the anchor score still looks fine.
        TD=$("$PY" "$REPO/scripts/td_rate.py" "$GEN_DIR" --json "$GEN_DIR/td_rate.json" 2>&1 | tr '\n' ' ') || TD="td_rate.py failed: $TD"
        status "$GG corpus: $TD"
        # Plan 042: does the size centre move? Reads this generation's
        # per-board TD rates against the gen00 baseline; advisory, logged.
        if [ "$SIZE_MODE" = centred ]; then
            SC=$("$PY" "$REPO/scripts/size_curriculum.py" "$RUN_DIR" --gen "$G" \
                    --advance "$SIZE_ADVANCE_TD" --step "$SIZE_STEP" --max-area "$SIZE_MAX_AREA" 2>&1) \
                || SC="size_curriculum.py failed: $SC"
            status "$GG $SC"
        fi
        touch "$GEN_DIR/.generated"
    fi
    # A resume that skipped generation may still hold a pending eval.
    eval_finish

    # -- 1b. the standing net check (plan 055 §6), in the background ------------
    # On this generation's generator and the corpus it just played, which it was not trained on.
    # Its own sidecar and threads; the result lands on status.md whenever it finishes.
    if [ "$NET_CHECK" = on ] && [ ! -e "$GEN_DIR/.trained" ] && [ ! -e "$GEN_DIR/.net_checked" ] \
        && [ ! -e "$GEN_DIR/.net_check_started" ]; then
        NC_NET="$(champion)"
        ensure_ts "$NC_NET"
        touch "$GEN_DIR/.net_check_started"
        (
            "$REPO/scripts/net_check.sh" "$NC_NET" "$GEN_DIR" "$GEN_DIR/net_check" "$NET_CHECK_CONFIG" ${NET_CHECK_LADDER:+"$NET_CHECK_LADDER"} \
                > "$GEN_DIR/net_check.log" 2>&1 \
                && status "$GG net check ($(basename "$NC_NET") on its own $GG corpus): $(cat "$GEN_DIR/net_check/net_check.txt")" \
                && touch "$GEN_DIR/.net_checked" \
                || status "WARN: $GG net check failed — see $GEN_DIR/net_check.log"
            rm -f "$GEN_DIR/.net_check_started"
        ) &
        status "$GG net check started in the background ($(basename "$NC_NET"))"
    fi

    # -- 1c. Monte Carlo value labels (plan 056) ---------------------------------
    # The generator's policy plays every train sample's drive out MC_LABEL_PLAYOUTS times; the window
    # trains on the means. Its own sidecar run on the card the generate phase just released.
    if [ "$MC_LABEL_PLAYOUTS" -gt 0 ] && [ ! -e "$GEN_DIR/.mc_labelled" ] && [ ! -e "$GEN_DIR/.trained" ]; then
        check_stop "before $GG mc-label"
        SECONDS=0
        MC_NET="$(champion)"
        # Train and val shards: val_value then scores the same label the net trains toward, which
        # is what lets restore-on-combined see the value head improve (gen02 restored its init on a
        # flat val_policy and discarded the value progress).
        MC_IN=""; for K in $TRAIN_SHARDS $VAL_SHARDS; do MC_IN="$MC_IN $GEN_DIR/shard$K.jsonl"; done
        # Plan 069 item 4b: labels streamed with the generation leave nothing to do; any shard they
        # missed is labelled below (the tools skip a shard whose output exists).
        MC_MISSING=0; for K in $TRAIN_SHARDS $VAL_SHARDS; do [ -s "$GEN_DIR/mc/shard$K.jsonl" ] || MC_MISSING=$((MC_MISSING + 1)); done
        if [ "$LABEL_STREAMING" = 1 ] && [ "$MC_MISSING" -eq 0 ]; then
            status "$GG mc-label: every train+val shard was labelled during generation (streamed)"
            MC_RC=0
        elif [ "$LABEL_VIA_HUB" = 1 ]; then
            # Plan 062: the same labels as a hub job — this box's worker on the sidecar(s) plus any
            # remote worker (tract). Same net, playouts, seed, output dir and summary lines.
            ensure_ts "$MC_NET"
            nn_server_start "$MC_NET" "$LABEL_SIDECARS"
            worker_start "$LABEL_PARALLEL_GAMES" "$GEN_DIR/mc_label.worker.log"
            status "$GG mc-label via the hub: $(echo $TRAIN_SHARDS $VAL_SHARDS | wc -w) train+val shards x $MC_LABEL_PLAYOUTS policy-only playouts per sample under $(basename "$MC_NET")${NN_SERVER_PID:+ via sidecar}, local x$LABEL_PARALLEL_GAMES$([ "$NN_BACKEND" = inproc ] && echo " in-process") + hub workers, items of $LABEL_CHUNK_SAMPLES samples"
            # shellcheck disable=SC2086
            "$HUB" job label --hub "$HUB_URL" --token-file "$HUB_TOKEN_FILE" --label "$GG mc-label" \
                --corpus $MC_IN --model "$MC_NET" --playouts "$MC_LABEL_PLAYOUTS" --seed "$((56000 + G))" \
                --chunk-samples "$LABEL_CHUNK_SAMPLES" --out-dir "$GEN_DIR/mc" $(job_wait_args) --wait >> "$GEN_DIR/mc_label.log" 2>&1
            MC_RC=$?
            worker_stop
            backend_check "$GEN_DIR/mc_label.worker.log" "$GG mc-label (local worker)"
        else
            ensure_ts "$MC_NET"
            nn_server_start "$MC_NET"
            status "$GG mc-label: $(echo $TRAIN_SHARDS $VAL_SHARDS | wc -w) train+val shards x $MC_LABEL_PLAYOUTS policy-only playouts per sample under $(basename "$MC_NET")${NN_SERVER_PID:+ via sidecar}"
            # shellcheck disable=SC2086
            "$UI" mc-label --corpus $MC_IN --model "$MC_NET" ${NN_SERVER_PID:+--nn-server "$NN_SOCKET"} \
                $([ "$NN_BACKEND" = inproc ] && echo "--nn-backend inproc") \
                --playouts "$MC_LABEL_PLAYOUTS" --parallel "$MC_LABEL_PARALLEL" --seed "$((56000 + G))" \
                --out-dir "$GEN_DIR/mc" 2>> "$GEN_DIR/mc_label.log"
            MC_RC=$?
            backend_check "$GEN_DIR/mc_label.log" "$GG mc-label"
        fi
        nn_server_stop
        [ "$MC_RC" -eq 75 ] && resumable_exit "$GG mc-label" "shards labelled so far are kept in $GEN_DIR/mc"
        [ "$MC_RC" -eq 0 ] || die "$GG mc-label failed — see $GEN_DIR/mc_label.log"
        for K in $TRAIN_SHARDS $VAL_SHARDS; do [ -s "$GEN_DIR/mc/shard$K.jsonl" ] || die "$GG mc/shard$K.jsonl missing"; done
        touch "$GEN_DIR/.mc_labelled"
        status "$GG mc-label done ($((SECONDS / 60)) min): $(grep -o '([0-9]* left unlabelled)' "$GEN_DIR/mc_label.log" | tr -dc '0-9\n' | awk '{s+=$1} END {print s+0}') trajectories left unlabelled"
    fi

    # -- 2. prepare -----------------------------------------------------------
    # Nothing downstream of training reads prepared_*, and prune_prepared
    # deletes them (with their marker) a generation later — so on a resume
    # past an already-trained generation, rebuilding them would cost minutes
    # and ~10 GB to feed a train step that is about to be skipped.
    check_stop "before $GG prepare"
    PREP_DIR="${PREPARED_ROOT:+$PREPARED_ROOT/$GG}"; PREP_DIR="${PREP_DIR:-$GEN_DIR}"
    if [ -n "$PREPARED_ROOT" ] && [ -e "$GEN_DIR/.prepared" ] && [ ! -e "$GEN_DIR/.trained" ] \
        && ! { ls -d "$PREP_DIR"/prepared_train/dims_* && ls -d "$PREP_DIR"/prepared_val/dims_*; } > /dev/null 2>&1; then
        status "$GG prepared dirs are not in $PREP_DIR (PREPARED_ROOT on another job's disk?): preparing again"
        rm -f "$GEN_DIR/.prepared"
    fi
    if [ -e "$GEN_DIR/.trained" ]; then
        DIMS_TRAIN=""; DIMS_VAL=""
    elif [ ! -e "$GEN_DIR/.prepared" ]; then
        SECONDS=0
        # The window, not just this generation — see WINDOW_GENS. Train and
        # val are pooled across the same span but keep the whole-shard split,
        # so held-out games stay disjoint from trained-on games in every
        # generation the window covers.
        TRAIN_IN=$(window_shards "$G" train)
        VAL_IN=$(window_shards "$G" val)
        [ -n "$TRAIN_IN" ] && [ -n "$VAL_IN" ] || die "$GG window is empty (WINDOW_GENS=$WINDOW_GENS)"
        WIN_GENS=$(echo "$TRAIN_IN" | tr ' ' '\n' | grep -c . )
        status "$GG prepare: window of $WINDOW_GENS gens -> $WIN_GENS train shards, $(echo "$VAL_IN" | tr ' ' '\n' | grep -c .) val shards, target $PREPARE_TARGET_ARGS${PREPARE_JOB_ARGS:+, $PREPARE_JOB_ARGS}"
        # shellcheck disable=SC2086
        "$PREPARE" --in $TRAIN_IN --out "$PREP_DIR/prepared_train" $PREPARE_TARGET_ARGS $PREPARE_JOB_ARGS >> "$LOG" 2>&1 \
            || die "$GG prepare (train) failed"
        # shellcheck disable=SC2086
        "$PREPARE" --in $VAL_IN --out "$PREP_DIR/prepared_val" $PREPARE_TARGET_ARGS $PREPARE_JOB_ARGS >> "$LOG" 2>&1 \
            || die "$GG prepare (val) failed"
        status "$GG prepare done ($((SECONDS / 60)) min), disk free $(free_gb)"
        touch "$GEN_DIR/.prepared"
    fi
    if [ ! -e "$GEN_DIR/.trained" ]; then
        # Plan 042: the whole prepared dir, every dims_* inside it (see gen00).
        DIMS_TRAIN="$PREP_DIR/prepared_train"; DIMS_VAL="$PREP_DIR/prepared_val"
        ls -d "$DIMS_TRAIN"/dims_* > /dev/null 2>&1 && ls -d "$DIMS_VAL"/dims_* > /dev/null 2>&1 \
            || die "$GG prepared dims dirs missing"
    fi

    # -- 3. train ---------------------------------------------------------------
    check_stop "before $GG train"
    if [ ! -e "$GEN_DIR/.trained" ]; then
        SECONDS=0
        # Pick the .pt to warm-start from. `latest` (AGZ) continues the
        # unbroken training trajectory; `champion` rolls back to the last
        # promoted net. Either way the champion — not this — is what
        # generates games, so a rejection never changes who plays.
        # LATEST_FILE is written after every successful train below, so it
        # survives a resume without globbing models/ and guessing.
        TRAIN_CHAMP="$(champion)"
        CHAMP_PT="${TRAIN_CHAMP%.onnx}.pt"
        INIT_PT=""
        if [ "$WARM_START" = "on" ]; then
            if [ "$WARM_FROM" = "latest" ] && [ -s "$LATEST_FILE" ] && [ -f "$(cat "$LATEST_FILE")" ]; then
                INIT_PT="$(cat "$LATEST_FILE")"
            elif [ -f "$CHAMP_PT" ]; then
                INIT_PT="$CHAMP_PT"
            fi
        fi
        TRAIN_EPOCHS="$EPOCHS"; GEN_TRAIN_ARGS="$TRAIN_TARGET_ARGS"
        if [ -n "$INIT_PT" ] && [ -n "$NO_WARM_FROM" ] && [ "$INIT_PT" = "$NO_WARM_FROM" ]; then
            # Plan 071 R2: the scratch recipe (SCRATCH_*), in the shape of the net it replaces.
            ARCH_ARGS="$SCRATCH_ARCH_ARGS"
            [ -n "$ARCH_ARGS" ] || ARCH_ARGS="$(net_arch_args "$INIT_PT")" \
                || die "$GG: cannot read the shape of $INIT_PT (set SCRATCH_ARCH_ARGS)"
            TRAIN_EPOCHS="$SCRATCH_EPOCHS"
            GEN_TRAIN_ARGS="$TRAIN_COMMON_ARGS$TRAIN_PASS_ARGS $SCRATCH_TRAIN_ARGS $ARCH_ARGS"
            status "$GG train: not warm-starting from $(basename "$INIT_PT") (NO_WARM_FROM) — random init at lr $SCRATCH_LR, $SCRATCH_EPOCHS epochs, $SCRATCH_TRAIN_ARGS, $ARCH_ARGS"
            INIT_PT=""
        fi
        if [ -n "$INIT_PT" ]; then
            INIT_ARGS="--init $INIT_PT --lr $WARM_LR"
            WARM_NOTE="$(basename "$INIT_PT")"
            [ "$INIT_PT" = "$CHAMP_PT" ] || WARM_NOTE="$WARM_NOTE (not the champion — WARM_FROM=$WARM_FROM)"
            status "$GG train: warm start from $WARM_NOTE at lr $WARM_LR"
        else
            INIT_ARGS="--lr $SCRATCH_LR"
            [ "$WARM_START" = "on" ] && [ "$CHAMP_PT" != "$NO_WARM_FROM" ] \
                && status "WARN: $GG warm start wanted but no usable .pt (champion $CHAMP_PT) — training from random init at lr $SCRATCH_LR"
        fi
        # shellcheck disable=SC2086
        if ! "$PY" -m bbnn.train --data "$DIMS_TRAIN" --val-data "$DIMS_VAL" \
                --epochs "$TRAIN_EPOCHS" --device "$TRAIN_DEVICE" $INIT_ARGS \
                --select-on "$SELECT_ON" --eval-every "$EVAL_EVERY" \
                $GEN_TRAIN_ARGS \
                --out "$MODEL.pt" --onnx "$MODEL.onnx" --progress "$GEN_DIR/train.progress.json" \
                > "$GEN_DIR/train.log" 2>&1; then
            die "$GG training failed — see train.log"
        fi
        BEST=$(grep 'restored best-val weights' "$GEN_DIR/train.log" | tail -1)
        BASE=$(grep 'warm-start baseline' "$GEN_DIR/train.log" | tail -1)
        ensure_ts "$MODEL.onnx"
        status "$GG train done ($((SECONDS / 60)) min): ${BEST:-best-val line not found}${BASE:+ (warm-start baseline was${BASE##*val_value})}"
        # Plan 054 E1: did this fine-tune absorb the search's improvement? Score the new net and the
        # net that generated this generation on this generation's own held-out shards: a positive
        # dlogP(played) with dtop1 >= 0 and dvalMSE <= 0 is a generation that learned something.
        # Minutes, on the GPU the sidecar has just released; diagnostic only, never fatal.
        if [ "$ABSORB_PROBE" = on ] && [ -f "$CHAMP_PT" ]; then
            PROBE_IN=""; for K in $VAL_SHARDS; do [ -s "$GEN_DIR/shard$K.jsonl" ] && PROBE_IN="$PROBE_IN $GEN_DIR/shard$K.jsonl"; done
            rm -rf "$GEN_DIR/probe_val"
            # shellcheck disable=SC2086
            if [ -n "$PROBE_IN" ] && "$PREPARE" --in $PROBE_IN --out "$GEN_DIR/probe_val" $PREPARE_TARGET_ARGS >> "$LOG" 2>&1 \
                && "$PY" "$REPO/scripts/absorb_probe.py" --summary --val "$GEN_DIR/probe_val" \
                    "generator=$CHAMP_PT" "$GG=$MODEL.pt" > "$GEN_DIR/absorb.txt" 2>&1; then
                status "$GG absorption: $(grep '^ABSORB' "$GEN_DIR/absorb.txt" | sed 's/^ABSORB [^:]*: //')"
            else
                status "WARN: $GG absorption probe failed — see $GEN_DIR/absorb.txt"
            fi
            rm -rf "$GEN_DIR/probe_val"
        fi
        # Plan 056 §2: the value head against Monte Carlo truth, the new net paired with its generator.
        # Plan 065: VALUE_BENCH_2, a second benchmark (e.g. 20x11 states) scored the same way into
        # value_bench_2/; the first keeps its directory and status line.
        for VB in "value_bench|value bench|$VALUE_BENCH" "value_bench_2|value bench 2|$VALUE_BENCH_2"; do
            IFS='|' read -r VB_DIR VB_NAME VB_FILE <<< "$VB"
            [ -n "$VB_FILE" ] && [ -f "$VB_FILE" ] || continue
            ensure_ts "$TRAIN_CHAMP" "$MODEL.onnx"
            if "$REPO/scripts/value_bench.sh" "$VB_FILE" "$GEN_DIR/$VB_DIR" \
                    "generator=$TRAIN_CHAMP" "$GG=$MODEL.onnx" > "$GEN_DIR/$VB_DIR.log" 2>&1; then
                status "$GG $VB_NAME: $(grep -E '^VALUE_BENCH' "$GEN_DIR/$VB_DIR/summary.txt" | sed 's/^VALUE_BENCH_*//' | paste -sd'|')"
            else
                status "WARN: $GG $VB_NAME failed — see $GEN_DIR/$VB_DIR.log"
            fi
        done
        echo "$MODEL.pt" > "$LATEST_FILE"
        # Gateless: the net just trained generates the next generation,
        # unconditionally. The benchmark below measures it; it does not
        # decide anything. Written before the marker so a resume can never
        # see a trained generation whose net is not the generator.
        echo "$MODEL.onnx" > "$CHAMPION_FILE"
        touch "$GEN_DIR/.trained"
        status "$GG is the generator now (no gate — plan 030); benchmark follows"
        prune_prepared "$((G - 1))"
    fi
    [ -f "$MODEL.onnx" ] || die "$GG onnx export missing: $MODEL.onnx"

    # -- 3b. shadow lineage (plan 063 / exp073 follow-up, the user 2026-10-15) --------------------
    # A second net (e.g. the 96x8 + bigger heads) fine-tuned every generation on the same window with
    # the same recipe, from its own previous checkpoint. It never generates: it only learns, and is
    # scored against this generation's net (absorption on the held-out shards, value bench paired),
    # until it converges and the two play head to head. Off unless SHADOW_INIT names its first .pt.
    if [ -n "$SHADOW_INIT" ] && [ ! -e "$GEN_DIR/.shadow_trained" ]; then
        SHADOW_PREV="$SHADOW_INIT"; [ -s "$SHADOW_LATEST" ] && [ -f "$(cat "$SHADOW_LATEST")" ] && SHADOW_PREV="$(cat "$SHADOW_LATEST")"
        SHADOW_MODEL="$MODEL_DIR/${SHADOW_NAME}_$GG"
        DIMS_TRAIN="$PREP_DIR/prepared_train"; DIMS_VAL="$PREP_DIR/prepared_val"
        if [ ! -d "$DIMS_TRAIN" ] || [ ! -d "$DIMS_VAL" ]; then
            status "WARN: $GG shadow skipped — this generation's prepared dirs are gone"
        else
            SECONDS=0
            status "$GG shadow train: $(basename "$SHADOW_PREV") -> $(basename "$SHADOW_MODEL") (same window and recipe)"
            # shellcheck disable=SC2086
            if "$PY" -m bbnn.train --data "$DIMS_TRAIN" --val-data "$DIMS_VAL" \
                    --epochs "$EPOCHS" --device "$TRAIN_DEVICE" --init "$SHADOW_PREV" --lr "$WARM_LR" \
                    --select-on "$SELECT_ON" --eval-every "$EVAL_EVERY" $TRAIN_TARGET_ARGS \
                    --out "$SHADOW_MODEL.pt" --onnx "$SHADOW_MODEL.onnx" > "$GEN_DIR/shadow_train.log" 2>&1; then
                echo "$SHADOW_MODEL.pt" > "$SHADOW_LATEST"
                ensure_ts "$SHADOW_MODEL.onnx" "$MODEL.onnx"   # the shadow value bench pairs it with this generation's net
                status "$GG shadow train done ($((SECONDS / 60)) min): $(grep 'restored best-val weights' "$GEN_DIR/shadow_train.log" | tail -1)"
                PROBE_IN=""; for K in $VAL_SHARDS; do f="$GEN_DIR/mc/shard$K.jsonl"; [ -s "$f" ] || f="$GEN_DIR/shard$K.jsonl"; [ -s "$f" ] && PROBE_IN="$PROBE_IN $f"; done
                rm -rf "$GEN_DIR/shadow_probe_val"
                # shellcheck disable=SC2086
                if [ -n "$PROBE_IN" ] && "$PREPARE" --in $PROBE_IN --out "$GEN_DIR/shadow_probe_val" $PREPARE_TARGET_ARGS >> "$LOG" 2>&1 \
                    && "$PY" "$REPO/scripts/absorb_probe.py" --summary --val "$GEN_DIR/shadow_probe_val" \
                        "$GG=$MODEL.pt" "shadow=$SHADOW_MODEL.pt" > "$GEN_DIR/shadow_absorb.txt" 2>&1; then
                    status "$GG shadow vs $GG (held-out): $(awk '$1=="'"$GG"'"||$1=="shadow"{printf "%s KL %s logP %s P %s valMSE %s; ", $1, $4, $5, $6, $8}' "$GEN_DIR/shadow_absorb.txt")"
                else
                    status "WARN: $GG shadow absorption failed — see $GEN_DIR/shadow_absorb.txt"
                fi
                rm -rf "$GEN_DIR/shadow_probe_val"
                if [ -n "$VALUE_BENCH" ] && [ -f "$VALUE_BENCH" ] && "$REPO/scripts/value_bench.sh" "$VALUE_BENCH" "$GEN_DIR/shadow_value_bench" \
                        "$GG=$MODEL.onnx" "shadow=$SHADOW_MODEL.onnx" > "$GEN_DIR/shadow_value_bench.log" 2>&1; then
                    status "$GG shadow value bench: $(grep -E '^VALUE_BENCH' "$GEN_DIR/shadow_value_bench/summary.txt" | sed 's/^VALUE_BENCH_*//' | paste -sd'|')"
                else
                    status "WARN: $GG shadow value bench failed or skipped"
                fi
            else
                status "WARN: $GG shadow training failed — see $GEN_DIR/shadow_train.log"
            fi
        fi
        touch "$GEN_DIR/.shadow_trained"
    fi

    # -- 4. benchmark: fixed rung(s) + vs the frozen anchor ----------------------
    # Submitted, not waited for: it runs alongside the next generation (see
    # eval_submit). An already-evaluated generation just gets its report.
    check_stop "before $GG eval"
    if [ ! -e "$GEN_DIR/.evaluated" ] && [ $((G % DRIVE_EVAL_EVERY)) -ne 0 ] && [ "$G" -lt "$MAX_GENS" ]; then
        echo "SKIPPED" > "$GEN_DIR/verdict"
        touch "$GEN_DIR/.evaluated"
        status "$GG benchmark skipped (DRIVE_EVAL_EVERY=$DRIVE_EVAL_EVERY; next at gen$(printf '%02d' $(( (G / DRIVE_EVAL_EVERY + 1) * DRIVE_EVAL_EVERY ))))"
    elif [ ! -e "$GEN_DIR/.evaluated" ]; then
        eval_submit "$G"
    else
        eval_report "$G" "?"
    fi

    G=$((G + 1))
done

eval_finish
status "loop finished: $MAX_GENS generations done, generator $(basename "$(champion)")"
