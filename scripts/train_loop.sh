# ---- hub + local worker lifecycle (plan 041) --------------------------------
# The hub is idempotent to start: if one already answers on $HUB_PORT (a
# previous loop instance, or started by hand so remote workers could join
# early) it is reused and left running on exit.
HUB_PID=""
WORKER_PID=""
hub_start() {
    if "$HUB" status --hub "$HUB_URL" --token-file "$HUB_TOKEN_FILE" > /dev/null 2>&1; then
        log "hub already running on $HUB_URL; reusing"
        return 0
    fi
    if [ "$HUB_EXTERNAL" = 1 ]; then
        local w=0
        until "$HUB" status --hub "$HUB_URL" --token-file "$HUB_TOKEN_FILE" > /dev/null 2>&1; do
            w=$((w + 5))
            [ "$w" -gt "$HUB_WAIT_SECS" ] && die "no hub answers at $HUB_URL after ${HUB_WAIT_SECS}s (HUB_EXTERNAL=1: the loop never starts one)"
            sleep 5
        done
        status "using the external hub at $HUB_URL (HUB_EXTERNAL=1)"
        return 0
    fi
    # HUB_ALLOW_FROM (comma-separated addresses / CIDR networks): only these clients, plus loopback,
    # get the hub's pages and the web play app; workers' /ws stays open (token-authenticated).
    "$HUB" serve --bind "0.0.0.0:$HUB_PORT" --token-file "$HUB_TOKEN_FILE" --run-dir "$RUN_DIR" \
        ${HUB_ALLOW_FROM:+--allow-from "$HUB_ALLOW_FROM"} ${HUB_ALLOWED_COMMITS:+--allowed-commits "$HUB_ALLOWED_COMMITS"} \
        >> "$RUN_DIR/hub.log" 2>&1 &
    HUB_PID=$!
    local i=0
    until "$HUB" status --hub "$HUB_URL" --token-file "$HUB_TOKEN_FILE" > /dev/null 2>&1; do
        i=$((i + 1))
        if [ "$i" -gt 30 ] || ! kill -0 "$HUB_PID" 2>/dev/null; then
            die "hub did not come up on $HUB_URL in ${i}s — see hub.log"
        fi
        sleep 1
    done
    status "hub up (pid $HUB_PID, port $HUB_PORT, token $HUB_TOKEN_FILE)"
}
hub_stop() {
    [ -n "$HUB_PID" ] || return 0
    kill "$HUB_PID" 2>/dev/null
    wait "$HUB_PID" 2>/dev/null
    HUB_PID=""
}
# $1 = parallel games, $2 = log file (per phase, so a fallback warning is
# attributable); the sidecar socket is passed when the server is up.
# Run a command with BLOOD_MCTS_BUDGET set to $1, or as-is when $1 is empty.
with_budget() {
    local mode="$1"; shift
    if [ -n "$mode" ]; then BLOOD_MCTS_BUDGET="$mode" "$@"; else "$@"; fi
}
# One generation's games: a single job, or one job per GEN_SPLIT group side by side. Same seed
# layout either way (shard K of gen G starts at SEED_BASE + G*1e6 + K*1e5), so a split corpus has
# the seeds a single job would have had.
# Plan 069 item 4b: `job generate`'s streamed-label flags for a job writing shards $1 (the train and
# val ones among them are labelled), or nothing with LABEL_STREAMING=0. Same playouts, seed, output
# dir and items as the mc-label phase; the net is the job's own --model, the phase's MC_NET.
stream_label_args() {
    local k ks=""
    [ "$LABEL_STREAMING" = 1 ] && [ "$MC_LABEL_PLAYOUTS" -gt 0 ] || return 0
    for k in $1; do case " $TRAIN_SHARDS $VAL_SHARDS " in *" $k "*) ks="$ks $k" ;; esac; done
    [ -n "$ks" ] || return 0
    ks="${ks# }"
    echo "--mc-label-playouts $MC_LABEL_PLAYOUTS --mc-label-seed $((56000 + G)) --mc-label-out-dir $GEN_DIR/mc --mc-label-chunk-samples $LABEL_CHUNK_SAMPLES --mc-label-shards ${ks// /,}"
}
generate_jobs() {
    local gen_dir="$1" champ="$2" size_args="$3" group sizes iters shards games i=0 rc=0
    local -a pids=()
    if [ -z "$GEN_SPLIT" ]; then
        # shellcheck disable=SC2086
        with_budget "$GEN_BUDGET_MODE" "$HUB" job generate --hub "$HUB_URL" --token-file "$HUB_TOKEN_FILE" \
            --mode random-start --games "$GAMES_PER_SHARD" \
            --seed-base $((SEED_BASE + G * 1000000)) --shard-seed-stride 100000 \
            --mcts-iters "$MCTS_ITERS" --evaluator "$EVALUATOR" --model "$champ" \
            $size_args $EXPLORE_ARGS ${NEXT_DRIVE:+--next-drive} ${GEN_BOT_CONFIG:+--bot-config "$GEN_BOT_CONFIG"} \
            --shards "$NN_SHARDS" --heuristic-shards "$HEUR_SHARDS" --label "$GG generate" \
            $(stream_label_args "$NN_SHARDS $HEUR_SHARDS") \
            $(gen_out_flag) $(job_wait_args) --out-dir "$gen_dir" --wait >> "$gen_dir/generate.log" 2>&1
        return $?
    fi
    IFS=';' read -ra groups <<< "$GEN_SPLIT"
    for group in "${groups[@]}"; do
        IFS='@' read -r sizes iters shards games <<< "$group"
        log "$GG generate group $i: $games/shard at $iters, shards $shards, boards $sizes"
        # shellcheck disable=SC2086,SC2046
        env ${GEN_BUDGET_MODE:+BLOOD_MCTS_BUDGET=$GEN_BUDGET_MODE} "$HUB" job generate --hub "$HUB_URL" --token-file "$HUB_TOKEN_FILE" \
            --mode random-start --games "$games" \
            --seed-base $((SEED_BASE + G * 1000000)) --shard-seed-stride 100000 \
            --mcts-iters "$iters" --evaluator "$EVALUATOR" --model "$champ" \
            --board-sizes "$sizes" --cells-per-player "$SIZE_CELLS_PER_PLAYER" $EXPLORE_ARGS ${NEXT_DRIVE:+--next-drive} ${GEN_BOT_CONFIG:+--bot-config "$GEN_BOT_CONFIG"} \
            --shards "$shards" --heuristic-shards "" --label "$GG generate ($sizes at $iters)" \
            $(stream_label_args "${shards//,/ }") \
            $(gen_out_flag) $(job_wait_args) --out-dir "$gen_dir" --wait >> "$gen_dir/generate.$i.log" 2>&1 &
        pids+=($!)
        i=$((i + 1))
    done
    # 75 (drained at the deadline, or the hub lost) only when no group failed outright.
    local r
    for p in "${pids[@]}"; do
        wait "$p"; r=$?
        if [ "$r" -eq 75 ] && [ "$rc" -ne 1 ]; then rc=75; elif [ "$r" -ne 0 ]; then rc=1; fi
    done
    cat "$gen_dir"/generate.[0-9]*.log > "$gen_dir/generate.log" 2>/dev/null
    return $rc
}
worker_start() {
    local extra="" mem="" share="$1" k=2 e labels="${3:-0}" lflag=
    if [ "$LOCAL_WORKER" = off ]; then
        log "no local worker (LOCAL_WORKER=off): the phase runs on the hub's other workers"
        return 0
    fi
    [ -n "$NN_SERVER_PID" ] && extra="--nn-server $NN_SOCKET"
    # Plan 066: one worker, its nets in-process (NN_EXTRA is empty: no sidecars were started).
    [ "$NN_BACKEND" = inproc ] && extra="--nn-backend inproc"
    [ -n "$WORKER_MEM_FLOOR_MB" ] && mem="--mem-floor-mb $WORKER_MEM_FLOOR_MB"
    # Plan 069 item 4b: label-only streams, on the first local worker only.
    [ "$labels" -gt 0 ] && lflag="--label-streams $labels"
    # One worker per sidecar, the streams split evenly (the first takes the remainder).
    [ "${#NN_EXTRA[@]}" -gt 0 ] && share=$(($1 / (${#NN_EXTRA[@]} + 1)))
    # shellcheck disable=SC2086
    "$WORKER" --hub "ws://$HUB_HOST:$HUB_PORT/ws" --token-file "$HUB_TOKEN_FILE" \
        --name "local" --parallel-games $(($1 - share * ${#NN_EXTRA[@]})) --cache-dir "$WORKER_CACHE" $extra $mem $lflag \
        >> "$2" 2>&1 &
    WORKER_PID=$!
    log "local worker started (pid $WORKER_PID, x$(($1 - share * ${#NN_EXTRA[@]}))${lflag:+ + $labels label streams}${extra:+ ($extra)})"
    for e in "${NN_EXTRA[@]}"; do
        # shellcheck disable=SC2086
        "$WORKER" --hub "ws://$HUB_HOST:$HUB_PORT/ws" --token-file "$HUB_TOKEN_FILE" \
            --name "local$k" --parallel-games "$share" --cache-dir "$WORKER_CACHE-$k" --nn-server "${e#*:}" $mem \
            >> "$2" 2>&1 &
        WORKER_EXTRA+=($!)
        log "local worker $k started (pid $!, x$share via sidecar $k)"
        k=$((k + 1))
    done
}
