# ---- gen-0 bootstrap --------------------------------------------------------
# The loop needs a champion to generate from, but `models/` is gitignored, so a
# fresh clone has none. Rather than making a hand-copied .onnx a hard
# prerequisite, build one here the same way plan 020/021 built the original: a
# heuristic-only corpus (the teacher), prepared with the same train/val shard
# split, trained with best-val restore. Skipped entirely when a champion exists,
# so hosts that already have one are unaffected.
if [ ! -f "$(champion)" ]; then
    check_stop "before gen-0 bootstrap"
    GEN_DIR="$RUN_DIR/gen00"
    MODEL="$MODEL_DIR/bbnet_${TIER}_gen00"
    mkdir -p "$GEN_DIR"
    status "gen-0 bootstrap: $(basename "$(champion)") not found — building a champion from a heuristic corpus"

    if [ ! -e "$GEN_DIR/.generated" ]; then
        SECONDS=0
        status "gen00 generate: 8x$BOOTSTRAP_GAMES_PER_SHARD heuristic games, local x$BOOTSTRAP_PARALLEL_GAMES + hub workers, disk free $(free_gb)"
        # Plan 041: one hub job writes every shard; shard K's seeds are
        # SEED_BASE + K*1e5 + g (G=0 — disjoint from every gen), the layout
        # the per-shard processes used. Heuristic games need no sidecar.
        worker_start "$BOOTSTRAP_PARALLEL_GAMES" "$GEN_DIR/generate.worker.log"
        if ! "$HUB" job generate --hub "$HUB_URL" --token-file "$HUB_TOKEN_FILE" \
                --mode random-start --games "$BOOTSTRAP_GAMES_PER_SHARD" \
                --seed-base "$SEED_BASE" --shard-seed-stride 100000 \
                --mcts-iters "$MCTS_ITERS" --evaluator heuristic \
                $(size_gen_args) \
                --shards "$NN_SHARDS $HEUR_SHARDS" \
                --truncate --out-dir "$GEN_DIR" --wait > "$GEN_DIR/generate.log" 2>&1; then
            worker_stop
            die "gen00 generate failed — see generate.log, hub.log and generate.worker.log"
        fi
        worker_stop
        GAMES=0
        for K in $NN_SHARDS $HEUR_SHARDS; do
            [ -s "$GEN_DIR/shard$K.jsonl" ] || die "gen00 shard$K.jsonl empty/missing — see generate.log"
            GAMES=$((GAMES + $(wc -l < "$GEN_DIR/shard$K.jsonl")))
        done
        status "gen00 generate done ($((SECONDS / 60)) min): $GAMES/$((BOOTSTRAP_GAMES_PER_SHARD * 8)) games"
        # Plan 042: the heuristic bootstrap corpus doubles as the per-board
        # TD-rate baseline the size curriculum measures the net against.
        "$PY" "$REPO/scripts/td_rate.py" "$GEN_DIR" --json "$GEN_DIR/td_rate.json" > /dev/null 2>&1 \
            && [ "$SIZE_MODE" != fixed ] && [ ! -s "$RUN_DIR/size_baseline.json" ] \
            && cp "$GEN_DIR/td_rate.json" "$RUN_DIR/size_baseline.json" \
            && status "gen00 corpus is the size baseline: $("$PY" "$REPO/scripts/td_rate.py" "$GEN_DIR" | head -1)"
        touch "$GEN_DIR/.generated"
    fi

    if [ ! -e "$GEN_DIR/.prepared" ]; then
        SECONDS=0
        TRAIN_IN=""; VAL_IN=""
        for K in $TRAIN_SHARDS; do TRAIN_IN="$TRAIN_IN $GEN_DIR/shard$K.jsonl"; done
        for K in $VAL_SHARDS; do VAL_IN="$VAL_IN $GEN_DIR/shard$K.jsonl"; done
        # shellcheck disable=SC2086
        "$PREPARE" --in $TRAIN_IN --out "$GEN_DIR/prepared_train" $PREPARE_TARGET_ARGS >> "$LOG" 2>&1 \
            || die "gen00 prepare (train) failed"
        # shellcheck disable=SC2086
        "$PREPARE" --in $VAL_IN --out "$GEN_DIR/prepared_val" $PREPARE_TARGET_ARGS >> "$LOG" 2>&1 \
            || die "gen00 prepare (val) failed"
        status "gen00 prepare done ($((SECONDS / 60)) min), target $PREPARE_TARGET_ARGS"
        touch "$GEN_DIR/.prepared"
    fi
    # Plan 042: hand the trainer the whole prepared dir — it reads every
    # dims_* subdir (batches never mix boards). `head -1` here used to drop
    # every board but the first, silently.
    DIMS_TRAIN="$GEN_DIR/prepared_train"; DIMS_VAL="$GEN_DIR/prepared_val"
    ls -d "$DIMS_TRAIN"/dims_* > /dev/null 2>&1 && ls -d "$DIMS_VAL"/dims_* > /dev/null 2>&1 \
        || die "gen00 prepared dims dirs missing"

    if [ ! -e "$GEN_DIR/.trained" ]; then
        SECONDS=0
        # shellcheck disable=SC2086
        if ! "$PY" -m bbnn.train --data "$DIMS_TRAIN" --val-data "$DIMS_VAL" \
                --epochs "$EPOCHS" --device "$TRAIN_DEVICE" \
                $TRAIN_TARGET_ARGS \
                --out "$MODEL.pt" --onnx "$MODEL.onnx" \
                > "$GEN_DIR/train.log" 2>&1; then
            die "gen00 training failed — see train.log"
        fi
        BEST=$(grep 'restored best-val weights' "$GEN_DIR/train.log" | tail -1)
        status "gen00 train done ($((SECONDS / 60)) min): ${BEST:-best-val line not found}"
        touch "$GEN_DIR/.trained"
        echo "$MODEL.pt" > "$LATEST_FILE"   # head of the training trajectory
    fi
    [ -f "$MODEL.onnx" ] || die "gen00 onnx export missing: $MODEL.onnx"

    # No promotion gate: with no incumbent, this net *is* the champion. Its
    # strength is measured by gen01's report card against the fixed rungs.
    echo "$MODEL.onnx" > "$CHAMPION_FILE"
    status "gen-0 bootstrap done: champion is now $(basename "$MODEL.onnx")"
fi

