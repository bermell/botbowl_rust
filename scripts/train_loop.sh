    echo "$a"
}
# How a generate job treats shards already on disk: resume them, or start over.
gen_out_flag() { if [ "$GEN_RESUME" = on ]; then echo --resume; else echo --truncate; fi; }
# gen_progress DIR TARGET_GAMES: games (first records) and follow-on records on disk.
gen_progress() {
    local lines=0 follow=0 f
    for f in "$1"/shard*.jsonl; do
        [ -f "$f" ] || continue
        lines=$((lines + $(wc -l < "$f")))
        follow=$((follow + $(grep -c '"drive":"2"' "$f")))
    done
    echo "$((lines - follow))/$2 games (+$follow follow-on drives) on disk"
}
# A hub job client exited 75: the deadline drained it, or its hub was lost. Everything written is
# kept; the next launch resubmits with what is on disk.
resumable_exit() {
    status "$1 stopped before the end (deadline or hub lost)${2:+: $2} — exiting cleanly; the next launch resumes it"
    exit 75
}
# Free disk in GiB. `df -g` is macOS-only; -BG/-k are the portable GNU spellings.
# Of the run dir's file system (the checkout's on the training box, where the run dir is in it).
free_gb() {
    if df -BG "$RUN_DIR" >/dev/null 2>&1; then
        df -BG "$RUN_DIR" | awk 'NR==2{gsub(/G/,"",$4); print $4"G"}'
    else
        df -k "$RUN_DIR" | awk 'NR==2{printf "%dG", $4/1048576}'
    fi
}

# ---- sliding training window ------------------------------------------------
# Shard files of kind `train`|`val` across the WINDOW_GENS generations ending
# at generation $1. Generations that never finished generating are skipped
# rather than half-included, and gen00 (the heuristic bootstrap corpus) ages
# out on its own once the window slides past it.
window_shards() {
    local g="$1" kind="$2" first i k d shards out=""
    first=$((g - WINDOW_GENS + 1))
    [ "$first" -lt 0 ] && first=0
    case "$kind" in
        train) shards="$TRAIN_SHARDS" ;;
        val)   shards="$VAL_SHARDS" ;;
        *)     return 1 ;;
    esac
    for i in $(seq "$first" "$g"); do
        d="$RUN_DIR/$(printf 'gen%02d' "$i")"
        [ -e "$d/.generated" ] || continue
        for k in $shards; do
            # Plan 056: a generation's MC-labelled copy of a shard replaces the raw one, train and val
            # alike, so val_value measures progress toward the label being trained.
            if [ "$MC_LABEL_PLAYOUTS" -gt 0 ] && [ -s "$d/mc/shard$k.jsonl" ]; then
                out="$out $d/mc/shard$k.jsonl"
            elif [ -s "$d/shard$k.jsonl" ]; then
                out="$out $d/shard$k.jsonl"
            fi
        done
    done
    echo "$out"
}

# prepared_train + prepared_val run ~3.3 GB per generation at a window of one,
# and scale with the window — 10 generations x a 3-wide window would want
# ~100 GB against the ~91 GB free when this was written. They are fully
# regenerable from the shards, so drop the previous generation's once the
# current one has trained. The .prepared marker goes with them: leaving it
# behind would make a resume skip prepare and then die on missing dims dirs.
prune_prepared() {
    local pg pd
    pg="$RUN_DIR/$(printf 'gen%02d' "$1")"
    pd="${PREPARED_ROOT:+$PREPARED_ROOT/$(printf 'gen%02d' "$1")}"; pd="${pd:-$pg}"
    [ -d "$pg" ] || return 0
    [ -d "$pd/prepared_train" ] || [ -d "$pd/prepared_val" ] || return 0
    rm -rf "$pd/prepared_train" "$pd/prepared_val"
    rm -f "$pg/.prepared"
    log "pruned prepared_* from $(basename "$pg") (regenerable from its shards)"
}

# ---- nn sidecar lifecycle (plan 024 Stage 5) --------------------------------
# One server for the whole phase, torn down before the train phase so the
# trainer gets the whole card. A dead server is *not* fatal: the Rust client
# falls back to tract, so a shard gets slower but still finishes, which
# preserves the loop's existing "a dead shard is a warning" semantics.
NN_SERVER_PID=""
nn_server_start() {
    [ "$NN_SERVER" = "on" ] || return 0
    local model="$1"
    [ -f "${model%.onnx}.pt" ] || {
        status "WARN: no ${model%.onnx}.pt beside the champion — sidecar needs the trainer's own weights; running on tract"
        return 0
    }
    rm -f "$NN_SOCKET"
    "$PY" "$REPO/scripts/nn_server.py" --socket "$NN_SOCKET" --device cuda \
        --model "$model" --stats-every 300 \
        $([ "$NN_CANVAS" = off ] || echo "--canvas $NN_CANVAS") >> "$RUN_DIR/nn_server.log" 2>&1 &
    NN_SERVER_PID=$!
    # Warm-up loads the net, traces it and captures 12 CUDA graphs; the
    # socket only appears once the batcher is ready, so waiting for the
    # socket is exactly the right readiness signal.
    local i=0
    while [ ! -S "$NN_SOCKET" ]; do
        i=$((i + 1))
        if [ "$i" -gt 120 ] || ! kill -0 "$NN_SERVER_PID" 2>/dev/null; then
            status "WARN: nn_server did not come up in ${i}s — see nn_server.log; shards will use tract"
            NN_SERVER_PID=""
            return 0
        fi
        sleep 1
    done
    status "nn_server up (pid $NN_SERVER_PID, $(basename "$model"), socket $NN_SOCKET)"
    # $2 (generate only): the number of sidecars; the extra ones serve the extra local workers.
    local n="${2:-1}" k sock pid
    for k in $(seq 2 "$n"); do
        sock="${NN_SOCKET%.sock}-$k.sock"; rm -f "$sock"
        "$PY" "$REPO/scripts/nn_server.py" --socket "$sock" --device cuda \
            --model "$model" --stats-every 300 \
            $([ "$NN_CANVAS" = off ] || echo "--canvas $NN_CANVAS") >> "$RUN_DIR/nn_server.$k.log" 2>&1 &
        pid=$!
        i=0
        while [ ! -S "$sock" ] && kill -0 "$pid" 2>/dev/null && [ "$i" -le 120 ]; do i=$((i + 1)); sleep 1; done
        if [ -S "$sock" ]; then
            NN_EXTRA+=("$pid:$sock")
            status "nn_server $k up (pid $pid, socket $sock)"
        else
            kill "$pid" 2>/dev/null
            status "WARN: nn_server $k did not come up — see nn_server.$k.log; one sidecar fewer"
        fi
    done
}
# ---- in-process backend (plan 066) -------------------------------------------
# ensure_ts NET.onnx...: NET.ts beside each NET.onnx for the in-process backend, exported from
# NET.pt by bbnn.export_ts (the sidecar's trace of forward_masked, staged like NN_CANVAS). Idempotent:
# an existing .ts newer than its .pt is kept. The hub ships the .ts with the ONNX to its workers
# (protocol v20), so exporting before a job is submitted is all a worker needs. A net with no .pt
# cannot be exported and is fatal here — never a quiet tract run later.
ensure_ts() {
    [ "$NN_BACKEND" = inproc ] || return 0
    local onnx pt ts canvas
    canvas="$NN_CANVAS"; [ "$canvas" = off ] && canvas="$((BUILD_H + 2))x$((BUILD_W + 2))"
    for onnx in "$@"; do
        [ -n "$onnx" ] && [ -f "$onnx" ] || continue
        pt="${onnx%.onnx}.pt"; ts="${onnx%.onnx}.ts"
        [ -s "$ts" ] && [ "$ts" -nt "$pt" ] && continue
        [ -f "$pt" ] || die "NN_BACKEND=inproc: no $(basename "$pt") beside $onnx to export $(basename "$ts") from (python -m bbnn.from_onnx can rebuild one)"
        "$PY" -m bbnn.export_ts "$pt" --out "$ts" --canvas "$canvas" >> "$LOG" 2>&1 \
            || die "bbnn.export_ts failed for $pt — see loop.log"
        log "exported $(basename "$ts") (canvas $canvas)"
    done
}
# backend_check LOG WHAT: a phase's NN work must have run where NN_BACKEND says. A forward that fell
# back to tract (NN_SERVER_FALLBACK, both backends) or an in-process phase whose log never shows a
# net loaded in-process gets a WARN line on status.md: the corpus is still right, just made at CPU
# speed, which is the failure that otherwise goes unnoticed for a whole generation.
backend_check() {
    local f="$1" what="$2"
    [ "$LOCAL_WORKER" = off ] && return 0   # no local worker, so no log of its own to check
    grep -q 'NN_SERVER_FALLBACK' "$f" 2>/dev/null \
        && status "WARN: $what fell back to tract (NN_SERVER_FALLBACK) — see $f"
    if [ "$NN_BACKEND" = inproc ] && ! grep -q 'NN_INPROC loaded' "$f" 2>/dev/null; then
        status "WARN: $what never loaded a net in-process (NN_BACKEND=inproc) — see $f"
    fi
    return 0
}
