#!/usr/bin/env bash
# Weekend generation loop for the 14x7 tier (plan 022).
#
# Regime per generation (plan 021 §Next steps 3):
#   generate (8x$EVALUATOR shards from the champion — pure self-play since
#      2026-09-11: gen09 went 30-0-0 (pts 1.000) vs the mcts-heuristic rung,
#      so the heuristic hedge's diversity value looked marginal; dropped it
#      for cleaner data, accepting a slower generate phase (8 nn shards on
#      the sidecar instead of 5) — see runs/loop14x7/status.md)
#   -> prepare (train = shards 0-3,5,6; val = shards 4,7 — one held-out shard
#      per generation, pooled across the last WINDOW_GENS generations; policy
#      label $POLICY_TARGET, completed-Q by default since plan 032 #7)
#   -> train (warm-started from the previous net's .pt, best-val restore on
#      $SELECT_ON, ONNX export)
#   -> the new net becomes the generator unconditionally (gateless since
#      plan 030, 2026-09-11 — AlphaZero's arrangement; the gate never changed
#      a decision in nine generations and cost ~30% of the cycle)
#   -> benchmark: $ANCHOR_GAMES paired games vs a *frozen* anchor net plus the
#      $EVAL_RUNGS fixed rung(s). A single score is a point on a curve
#      (SE ~0.07 at 40 games), the 3-gen rolling mean is the number to read
#      (scripts/anchor_curve.py); REGRESSION/PLATEAU flags are advisory and
#      the operator rolls back by hand — every net stays on disk.
#
# On a host with no champion yet (models/ is gitignored, so a fresh clone has
# none), a one-off gen-0 bootstrap runs first: a heuristic-only corpus, prepared
# and trained the same way, becomes the initial champion. Skipped when one exists.
#
# Launch (survives logout, prevents sleep — the script re-execs itself under
# caffeinate on macOS, systemd-inhibit on Linux):
#   nohup scripts/train_loop.sh > /dev/null 2>&1 &
# Monitor over ssh:
#   tail -f runs/loop14x7/status.md          # one line per phase
#   tail -f runs/loop14x7/loop.log           # detail
#   tail -f runs/loop14x7/gen01/shard0.log   # a generator's per-game progress
# Stop cleanly:
#   touch runs/loop14x7/STOP                 # exits at the next phase boundary
# Resume after a stop/crash: just relaunch — completed phases are skipped via
# .done markers, the champion is persisted in champion.txt.
#
# DO NOT EDIT THIS FILE WHILE A RUN IS IN FLIGHT. bash parses a whole
# compound command — the entire generation `while` loop below — before
# executing it, so an edit inside it does not take effect in the running
# process; and bash re-reads the *rest* of the file by byte offset, so
# inserting or deleting lines can make it resume mid-command. Running stale
# code is the benign outcome, not the guaranteed one. It bit on 2026-09-02:
# the eval-parallelisation commit landed 7 minutes after launch and gen01's
# eval silently ran the old serial path for 2 minutes before it was caught.
# Edit, commit, then stop and relaunch — the markers make that cheap.

set -u

# Keep the machine awake for the whole run. macOS uses caffeinate, Linux uses
# systemd-inhibit; on a host with neither we just run (and may be suspended).
if [ -z "${TRAIN_LOOP_NOSLEEP:-}" ]; then
    export TRAIN_LOOP_NOSLEEP=1
    if command -v caffeinate >/dev/null 2>&1; then
        exec caffeinate -is "$0" "$@"
    elif command -v systemd-inhibit >/dev/null 2>&1; then
        exec systemd-inhibit --what=sleep:idle --who="train_loop.sh" \
            --why="botbowl generation loop" --mode=block "$0" "$@"
    fi
fi

REPO="$(cd "$(dirname "$0")/.." && pwd)"
cd "$REPO"

# ---- board size (plan 042) --------------------------------------------------
# SIZE_MODE=fixed    one board, the historical 14x7/4 loop. BUILD_* is both the
#                    compiled capacity and the board every game is played on.
# SIZE_MODE=centred  each game draws its board from a log-normal in playable
#                    area around a moving centre, mixed with a uniform floor so
#                    every size stays in every generation. The centre starts
#                    at SIZE_CENTRE and scripts/size_curriculum.py advances it
#                    from the corpus's own per-board TD rate after every
#                    generate phase (advisory: overwrite size_centre.txt by
#                    hand at any phase boundary). BUILD_* is the *capacity* —
#                    the largest board the sampler may draw — and the eval
#                    ladder runs every rung on each of EVAL_BOARD_SIZES.
# SIZE_MODE=list     as centred, but the fixed weighted list SIZE_LIST
#                    (`12x5,14x7:3,16x9`) instead of a moving centre.
# Board size is a *build-time* capacity (FullPitch arrays are sized by it), so
# a mixed run builds at the largest board it will ever sample — 16x9/6 covers
# plan 039's table; 20x11/7 is the next tier and needs its own build.
SIZE_MODE="${SIZE_MODE:-fixed}"             # fixed|centred|list
if [ "$SIZE_MODE" = fixed ]; then
    BUILD_W="${BUILD_W:-14}"; BUILD_H="${BUILD_H:-7}"; BUILD_PLAYERS="${BUILD_PLAYERS:-4}"
else
    BUILD_W="${BUILD_W:-16}"; BUILD_H="${BUILD_H:-9}"; BUILD_PLAYERS="${BUILD_PLAYERS:-6}"
fi
export BOARD_SIZE_W="$BUILD_W" BOARD_SIZE_H="$BUILD_H" BOARD_PLAYERS="$BUILD_PLAYERS"
TIER="${TIER:-${BUILD_W}x${BUILD_H}}"        # model-name tag: bbnet_${TIER}_genNN
[ "$SIZE_MODE" = fixed ] || TIER="${TIER_OVERRIDE:-mix${BUILD_W}x${BUILD_H}}"
SIZE_CENTRE="${SIZE_CENTRE:-98}"            # initial playable area (14x7 = 98)
SIZE_TEMPERATURE="${SIZE_TEMPERATURE:-0.3}" # std-dev of ln(area/centre)
SIZE_FLOOR="${SIZE_FLOOR:-0.2}"             # uniform share over every legal board
SIZE_ASPECT="${SIZE_ASPECT:-1.5-2.8}"       # playable w/h band the grid keeps
SIZE_CELLS_PER_PLAYER="${SIZE_CELLS_PER_PLAYER:-26}"
SIZE_LIST="${SIZE_LIST:-12x5,14x7:3,16x9}"  # SIZE_MODE=list only
SIZE_ADVANCE_TD="${SIZE_ADVANCE_TD:-0.75}"  # relative TD/drive at/above centre that moves it
SIZE_STEP="${SIZE_STEP:-1.25}"              # centre *= this on advance
SIZE_MAX_AREA="${SIZE_MAX_AREA:-$((BUILD_W * BUILD_H))}"
# Smallest playable area the centred grid draws. Plan 042 E0 (2026-09-23, 480
# games): at the density rule's 26 cells/player every board of area <= 60 is a
# 2v2, and there the champion's attack ratio against the scripted mirror was
# 0.95x — it scored *less* than two scripted bots do — against 1.60-1.97x on
# every larger board. Those games are a scoring free-for-all in which skill
# does not express, so their policy targets are noise; at centre 98 with floor
# 0.2 they would have been ~12% of the corpus. 70 is the bound that clears
# every team-size-2 board. Unset for the old behaviour (no lower bound).
SIZE_MIN_AREA="${SIZE_MIN_AREA:-70}"
# Fixed eval set, independent of the training centre — that independence is
# what keeps the per-size ladder honest. Every rung (and the anchor) runs once
# per board; cost scales with the count.
EVAL_BOARD_SIZES="${EVAL_BOARD_SIZES:-12x5,14x7,16x9}"

# ---- knobs (env-overridable) ------------------------------------------------
MAX_GENS="${MAX_GENS:-30}"
GAMES_PER_SHARD="${GAMES_PER_SHARD:-600}"   # 8 shards -> 4800 games/generation
MCTS_ITERS="${MCTS_ITERS:-1000}"
EVAL_GAMES="${EVAL_GAMES:-30}"              # per fixed ladder rung, paired Home/Away
# Fixed rungs kept in the report card. `random` read 1.000 in every one of
# nine generations and `scripted` sits at 0.87-0.95 where 30 games is noise.
# mcts-heuristic saturated too and was dropped 2026-09-12: gen08-12 scored
# 0.900 1.000 0.950 0.950 0.983 (gen12 W29 D1 L0), so it no longer separates
# generations and its 30 games only cost eval time. Empty = no fixed rungs,
# leaving the anchor as the sole measurement. Set it again (or pass a new
# rung name) once there is a stronger scripted bot worth benchmarking against.
EVAL_RUNGS="${EVAL_RUNGS:-}"
# The vs-champion rung separately, because it is the only rung the gate
# reads and the only one that is underpowered. At 30 games the points score
# has SE ~0.077, so the 0.55 gate sits 0.65 SE above 0.50 and passes an
# *equal* net about a quarter of the time. At 100 it is SE ~0.042 and 1.2 SE,
# roughly halving that false-promotion rate. The fixed rungs stay at 30:
# they are already decisive (p < 0.01) and are the cheap information here.
MIRROR_GAMES="${MIRROR_GAMES:-100}"         # pre-flight heuristic mirror match
# Budget history, and the correction that matters: 10 -> 15 (2026-09-17) ->
# 3 (2026-09-18).
#
# Plan 036's W6 said shrink; I argued against it and raised the budget instead,
# on the grounds that gen04 restored at epoch 9 of 10 and so was budget-bound.
# That reading was wrong. Under the adopted value-target recipe the whole
# validation curve is flat — total val_value spread across a 15-epoch run is
# ~0.009, against 0.08-0.10 under the old recipe — so the restore step is drawn
# from noise, not signal. gen04/05/06/07 restored at epochs 9, 7, 9 and 2; those
# are draws, not a trend, and "epoch 9" never meant the budget was binding.
#
# Plan 029 conclusion 4 had already measured the same thing from the other side:
# warm-started training barely moves the net at all (turnover at step 2,500 and
# 20,000, against 17,500-92,500 from scratch). Between generations val_policy
# falls hard (1.63 -> 1.15 over gen02-07); within a fine-tune it moves 0.005.
# The learning is in the data distribution changing, not in fitting longer.
#
# So W6 is adopted after all, for the correct reason: not "the value head turns
# over after epoch 1" but "the curve is flat, so the epochs do nothing". 3
# epochs gives back ~50 min of train phase per generation.
#
# This is the *budget*, not the fix. The reason the fine-tune has little to
# learn is plan 036's mechanism 1 — two thirds of every window was in the
# previous fine-tune's training set — and no epoch count addresses that. See
# plans/040 for the window/from-scratch experiment that does.
EPOCHS="${EPOCHS:-3}"
                                            # (was wins/N until 2026-09-02 — see eval_summary.py)
TRAIN_DEVICE="${TRAIN_DEVICE:-auto}"        # trainer device: auto|cpu|cuda|cuda:N
# Which leaf/prior source the bot plays with. `nn-value` = NN leaf values but
# *scripted* priors (dynamics.rs:258), which means the policy head is trained
# every generation and never used to play. That choice came from plan 020,
# which measured learned priors as actively harmful on gen-0: full-nn 0.75 vs
# nn-value 0.83 TDs/game. Plan 027 re-measured it three promotions later across
# 160 games at two budgets — 0.604 / 0.539 / 0.558, pooled 0.556, CI
# [0.486, 0.626] — and the sign has flipped. The result is not significant, but
# the claim that justified nn-value (learned priors are *worse*) no longer holds,
# and switching is what makes the policy head count for anything.
# Set EVALUATOR=nn-value to revert.
EVALUATOR="${EVALUATOR:-nn}"
# Coupled to the above, and wrong to change independently: value-only best-val
# restore is correct exactly while nothing consumes the policy head. See
# --select-on in bbnn/train.py.
SELECT_ON="${SELECT_ON:-combined}"
# Policy label (plan 032 #7, adopted 2026-09-08). `visits` is the AlphaZero
# target, the root's visit distribution. At 1000 iterations over a wide fan
# it has not converged: on roots with >30 children it agrees with the 16k
# reference only 0.21 of the time and points away from the move the bot
# actually played three times in four (plan 031 D2). `cq` is completed-Q,
# softmax(ln prior + q_mover/tau) with unvisited children filled by the
# visit-weighted mean Q — the search's *value* information folded into the
# label. Same data, init, seed and steps: Q7 (cq, tau 100) beat D7 (visits)
# 0.613 +/- 0.040, the largest single-variable gain in plan 032. Applied to
# the val set too, so best-val selection scores against the trained label;
# val_policy/val_top1 step-change at the switch and are not comparable
# across it, val_value is. Set POLICY_TARGET=visits to revert.
POLICY_TARGET="${POLICY_TARGET:-cq}"        # visits|cq
CQ_TAU="${CQ_TAU:-100}"                     # in Q points (1000 = one TD); only for cq
PREPARE_TARGET_ARGS="--policy-target $POLICY_TARGET"
[ "$POLICY_TARGET" = cq ] && PREPARE_TARGET_ARGS="$PREPARE_TARGET_ARGS --tau $CQ_TAU"
# Plan 036, adopted 2026-09-17 from gen04 on. The value head was fitting the
# window: measured on this run's own gen02 window, the baseline restored its
# best checkpoint at epoch 1 of 10 and val_value then degraded 16% of the
# label's variance over the remaining nine, while train value_loss fell
# monotonically. Both of the loop's own warm-started fine-tunes (gen02, gen03)
# restored inside epoch 0.
#
# Three knobs, measured together against the baseline on two windows (gen01
# from-scratch, gen02 warm-started), runs/exp036:
#
#   VALUE_BLEND=0.5   (W3) the value label becomes
#                     0.5*drive_outcome + 0.5*root_search_value, both
#                     mover-signed. The outcome is one dice-driven scalar per
#                     drive copied to all ~30 of its positions; the root value
#                     averages ~1000 leaf scores. Much the largest effect:
#                     restore step 5.75x later, and the post-optimum drift
#                     goes from 16% of label variance to 0.5%.
#   VALUE_WEIGHT=0.25 (W1) scales the value loss in the backward pass only —
#                     Leela Zero's MSE/4, adopted there after this same
#                     symptom. Worth 1.75x on its own.
#   PER_DRIVE_VALUE_WEIGHT=on
#                     (W4) weights each sample's value loss by 1/len(drive),
#                     so a drive contributes one unit of value gradient per
#                     epoch instead of one per position. The one clean
#                     same-label gain in the table: R^2 0.573 -> 0.591.
#
# Rejected, with the numbers, so nobody re-runs them:
#   W2 weight decay 1e-4 — inert on both windows (identical restore step and
#     R^2 to baseline) and added nothing on top of W1. Retry at 1e-3 if
#     anyone wants it; do not assume AlphaZero's SGD 1e-4 transfers to AdamW.
#   W5 prepare --dedup — found only 2.7% exact duplicates here (varied players
#     make collisions rare; plan 031 D3's 12.8% was the old identical-lineman
#     corpus) and cost policy quality on both windows. Not worth it.
#
# NOTE the value head's output is no longer calibrated as "expected score
# delta" — it is a blend. `nn-value` leaf scoring and td_rate.py consume the
# sign/ordering and are unaffected, and the manifest records the blend.
VALUE_BLEND="${VALUE_BLEND:-0.5}"           # W3; 1.0 = pure drive outcome
VALUE_WEIGHT="${VALUE_WEIGHT:-0.25}"        # W1; 1.0 = the old unweighted sum
PER_DRIVE_VALUE_WEIGHT="${PER_DRIVE_VALUE_WEIGHT:-on}"   # W4; on|off
PREPARE_TARGET_ARGS="$PREPARE_TARGET_ARGS --value-blend $VALUE_BLEND"
TRAIN_TARGET_ARGS="--value-weight $VALUE_WEIGHT"
[ "$PER_DRIVE_VALUE_WEIGHT" = on ] && TRAIN_TARGET_ARGS="$TRAIN_TARGET_ARGS --per-drive-value-weight"
# Validate every N optimizer steps instead of once per epoch (plan 031 D4/D5,
# adopted 2026-09-07). The warm-started fine-tunes gen04-07 all restored at
# epoch 0-2 of 10 because val_value bottoms out inside the first epoch or two
# and then climbs while val_policy is still falling; a per-epoch grid can only
# hand back the epoch-0 or epoch-1 weights, which is most of why those nets
# looked identical to their gen03 warm start. A finer grid lets best-val land
# on the real optimum. ~1 epoch of the 3-generation window is ~15-20k steps at
# batch 32, so 2500 is 6-8 checkpoints per epoch.
EVAL_EVERY="${EVAL_EVERY:-2500}"
# How the loop compounds (added 2026-09-03, after gen02 scored 0.450 against
# gen01 on the full 100-game rung despite a *better* val_value, 0.4026 vs
# 0.4126). Until now every generation trained a fresh net from random init on
# that one generation's 4800 games, so a generation was an independent draw
# from nearly the same distribution rather than a step on top of the last —
# promotion was a coin flip by construction. AlphaGo Zero does neither of
# those things: it keeps a single continuously-trained net (its "generations"
# are checkpoints of one SGD run) and samples every batch from the most
# recent 500,000 self-play games. These two knobs are the scaled-down
# version of both halves.
WINDOW_GENS="${WINDOW_GENS:-3}"             # train on the last N generations' shards
WARM_START="${WARM_START:-on}"              # seed each generation from a previous net's .pt
# Which net to seed from, and this one is easy to get backwards. In AlphaGo
# Zero the promotion gate decides *who generates self-play games*, not who
# gets trained further: the training net is one unbroken SGD run that never
# rolls back, and a rejected checkpoint still becomes the starting point of
# the next one. Only the "best player" used for generation is gated.
#   latest   — AGZ semantics. Training always moves forward from the last net
#              trained, promoted or not; only generation uses the champion.
#              A rejection costs you deployment, not the learning.
#   champion — roll back to the last promoted net on a rejection. Safer
#              against a generation that trains itself somewhere bad, but it
#              restarts from the same point every time it fails.
#
# Was `latest` from 2026-09-03 and produced gen03's promotion, then drifted:
# gen04 scored 0.440 against champion gen03 and gen05, warm-started from
# gen04, scored 0.380 — each generation continuing from the weakest net yet
# with nothing pulling it back. AGZ can never roll back because its training
# net keeps improving on a corpus orders of magnitude larger; at 4800
# games/gen and a 3-gen window the head just wanders. Switched to `champion`
# on 2026-09-05 after the second rejection. Revisit if the gate starts
# passing consistently again — `latest` is the better idea when it works.
# Gateless since 2026-09-11 (plan 030): the trained net *is* the next
# generator, so champion and latest coincide and `latest` is the natural
# spelling. Plan 032 #12 settled the alternative — a from-scratch retrain on
# the whole corpus scored 0.471 against this fine-tune's gen09 — so the
# 2e-4 warm start stays.
WARM_FROM="${WARM_FROM:-latest}"
# Warm start restores weights but not Adam's moment estimates (the .pt has to
# stay a bare state_dict — nn_server.py loads it directly), so the first steps
# of a warm-started run are taken with fresh moments. At the from-scratch
# 1e-3 those steps are large enough to undo the warm start; 2e-4 is the
# fine-tuning default that keeps it.
WARM_LR="${WARM_LR:-2e-4}"
SCRATCH_LR="${SCRATCH_LR:-1e-3}"            # used when there is nothing to warm-start from
# A .pt that must never be warm-started from, however the WARM_FROM rules
# would otherwise reach it. Exists for the from-scratch AlphaZero run: its
# gen-0 champion is a *randomly initialised* net (scripts/make_random_net.py),
# there only so generation has something to play with. Warm-starting gen01
# from random weights at WARM_LR would be the worst of both worlds — a
# fine-tuning learning rate applied to a net that has learned nothing — so
# name that .pt here and gen01 trains from random init at SCRATCH_LR instead.
# Every later generation warm-starts from gen01 as usual.
NO_WARM_FROM="${NO_WARM_FROM:-}"
BOOTSTRAP_GAMES_PER_SHARD="${BOOTSTRAP_GAMES_PER_SHARD:-$GAMES_PER_SHARD}"
                                            # gen-0 corpus when no champion exists
INIT_CHAMPION="${INIT_CHAMPION:-$REPO/models/bbnet_14x7_db.onnx}"
# Plan 024: batched GPU inference. `off` keeps the loop exactly as it was
# (tract on the CPU, no Python, no GPU during generate). Measured on this
# host at 8 shards x 4 parallel games: 2.62 s/game against tract's 9.93,
# i.e. 3.8x, using 4.3 cores against 5.3.
NN_SERVER="${NN_SERVER:-on}"                # on|off
NN_SOCKET="${NN_SOCKET:-/tmp/bbnn-loop.sock}"
# Concurrent games per *nn* shard. RAM-bound, not speed-bound: each
# in-flight game holds its own MCTS tree, and a tree high-waters around
# 400-500 MB at 1000 iters on this tier. Measured over 10 min in the exact
# production shape (5 nn + 3 heuristic + server) on this 15 GB box:
#   P=4 -> nn shards ~8.0 GB, 10.6 GB total, only 3 GB available  <-- too tight
#   P=2 -> ~7 GB total, 5-6 GB available, and barely slower
# Plans 020/021 record real OOM kills here, so 2 it is. Raise it on a box
# with more RAM: the throughput sweep peaked at 4.
PARALLEL_GAMES="${PARALLEL_GAMES:-2}"
# Plan 041: the generate phase is one local worker (plus remote ones), not
# 8 shard processes, so its concurrency is the worker's stream count. The
# old shape was 8 shards x PARALLEL_GAMES trees; the same tree count is the
# safe default here, and the RAM note above applies unchanged (one tree per
# stream, ~400-500 MB each at 1000 iters).
GEN_PARALLEL_GAMES="${GEN_PARALLEL_GAMES:-$((PARALLEL_GAMES * 8))}"
# The bootstrap corpus is heuristic-only: no sidecar, so nothing to batch
# for; it just wants the cores.
BOOTSTRAP_PARALLEL_GAMES="${BOOTSTRAP_PARALLEL_GAMES:-$(nproc 2>/dev/null || sysctl -n hw.ncpu 2>/dev/null || echo 8)}"
# Same knob for the eval phase, tuned separately. Eval has the box to
# itself (no generate shards competing), but each rung worker holds *two*
# MCTS trees — candidate and opponent — against a dataset worker's one, so
# the per-unit memory is roughly double. 4 workers ~ 8 trees, which is the
# same tree count the generate phase carries across all its shards.
# Was 4; measured during gen09's eval (2026-09-10) at 4 streams: ~58% of the
# 8 cores idle, the sidecar at mean batch 1.09 (latency-bound, ~380 us per
# single-sample forward). Re-measured 2026-09-11 at 6 streams (anchor
# backfill): still 37% idle, each search thread ~70% busy (the rest is the
# sidecar round trip), server 0.7 core, GPU ~70% at mean batch 1.16 and
# 2773 samples/s — 1.46x the x4 rate for 1.5x the streams, i.e. not yet
# GPU-bound. 8 streams is 16 trees at ~250 MB each; eval held 3.0 GB at 6
# against 10.7 GB available, so 8 fits with room.
EVAL_PARALLEL_GAMES="${EVAL_PARALLEL_GAMES:-8}"
NN_SERVER_RESTARTS="${NN_SERVER_RESTARTS:-3}"
SEED_BASE=10000000                          # gen G shard K: BASE + G*1e6 + K*1e5
                                            # (old corpora used 8e5.. and 2e6..)
RUN_DIR="${RUN_DIR:-$REPO/runs/loop14x7}"   # override both for dry runs so a
MODEL_DIR="${MODEL_DIR:-$REPO/models}"      # test never touches real models/
# Mixed-size runs keep their own run dir by default so a 14x7 run's markers
# and champion are never mistaken for a mixed one's.
[ "$SIZE_MODE" = fixed ] || RUN_DIR="${RUN_DIR_OVERRIDE:-$REPO/runs/loop$TIER}"
# Plan 030: the frozen benchmark opponent. gen03 was the last net promoted on
# merit under the gate and every plan-032 match is already on its scale (Q7
# 0.625, D7 0.396). Never retrain or overwrite it. Re-anchor (add a second,
# overlap three generations, then drop this one) once the rolling mean passes
# ~0.75 — a saturated anchor stops discriminating.
ANCHOR="${ANCHOR:-$MODEL_DIR/bbnet_14x7_gen03.onnx}"
ANCHOR_GAMES="${ANCHOR_GAMES:-40}"          # paired Home/Away on --seed 0, every generation
# -----------------------------------------------------------------------------

NN_SHARDS="0 1 2 3 4 5 6 7" # generated by the champion (nn-value); pure
                            # self-play since 2026-09-11 (heuristic hedge
                            # dropped — gen09 was already 30-0-0 vs it)
HEUR_SHARDS=""              # kept as a knob, empty by default now
TRAIN_SHARDS="0 1 2 3 5 6"
VAL_SHARDS="4 7"            # held out whole, one per generation

# Board size is a *build-time* choice (botbowl-engine/build.rs), so the 14x7
# binaries and a default-board `cargo test --workspace` would otherwise evict
# each other from a shared target dir and force a full rebuild on every switch.
# Nested under /target so the existing .gitignore entry still covers it.
CARGO_TARGET_DIR="${CARGO_TARGET_DIR:-$REPO/target/${BUILD_W}x${BUILD_H}}"
export CARGO_TARGET_DIR
UI="$CARGO_TARGET_DIR/release/botbowl-ui"
PREPARE="$CARGO_TARGET_DIR/release/prepare"
# Plan 041: the eval phase runs on the hub. The daemon lives for the whole
# loop (remote workers stay connected across generations); the *local*
# worker is started per phase, inside the sidecar's lifetime, because its
# loaded nets hold the sidecar socket. Remote machines join with
#   botbowl-worker --hub ws://<this box>:$HUB_PORT/ws --token-file <copy of $HUB_TOKEN_FILE>
HUB="$CARGO_TARGET_DIR/release/botbowl-hub"
WORKER="$CARGO_TARGET_DIR/release/botbowl-worker"
HUB_PORT="${HUB_PORT:-7777}"
HUB_URL="http://127.0.0.1:$HUB_PORT"
HUB_TOKEN_FILE="${HUB_TOKEN_FILE:-$RUN_DIR/hub.token}"
WORKER_CACHE="$RUN_DIR/worker-cache"
PY="$REPO/train/.venv/bin/python"
SUMMARY="$REPO/scripts/eval_summary.py"

mkdir -p "$RUN_DIR" "$MODEL_DIR"
LOG="$RUN_DIR/loop.log"
STATUS="$RUN_DIR/status.md"
CHAMPION_FILE="$RUN_DIR/champion.txt"
# The last net trained, promoted or not — the head of the training trajectory
# when WARM_FROM=latest. Distinct from champion.txt, which is the last net
# that *passed the gate* and is therefore the only one that generates games.
LATEST_FILE="$RUN_DIR/latest_net.txt"

log() { echo "[$(date '+%F %T')] $*" >> "$LOG"; }
status() { echo "[$(date '+%F %T')] $*" >> "$STATUS"; log "STATUS: $*"; }
die() { status "FATAL: $*"; exit 1; }
check_stop() {
    if [ -e "$RUN_DIR/STOP" ]; then
        status "STOP file present — exiting cleanly ($1)"
        exit 0
    fi
}
champion() { cat "$CHAMPION_FILE"; }
# Free disk in GiB. `df -g` is macOS-only; -BG/-k are the portable GNU spellings.
free_gb() {
    if df -BG . >/dev/null 2>&1; then
        df -BG . | awk 'NR==2{gsub(/G/,"",$4); print $4"G"}'
    else
        df -k . | awk 'NR==2{printf "%dG", $4/1048576}'
    fi
}

# ---- sliding training window ------------------------------------------------
# Shard files of kind `train`|`val` across the WINDOW_GENS generations ending
# at generation $1. Generations that never finished generating are skipped
# rather than half-included, and gen00 (the heuristic bootstrap corpus) ages
# out on its own once the window slides past it.
window_shards() {
    local g="$1" kind="$2" first i k d shards out=""
    first=$((g - WINDOW_GENS + 1))
    [ "$first" -lt 0 ] && first=0
    case "$kind" in
        train) shards="$TRAIN_SHARDS" ;;
        val)   shards="$VAL_SHARDS" ;;
        *)     return 1 ;;
    esac
    for i in $(seq "$first" "$g"); do
        d="$RUN_DIR/$(printf 'gen%02d' "$i")"
        [ -e "$d/.generated" ] || continue
        for k in $shards; do
            [ -s "$d/shard$k.jsonl" ] && out="$out $d/shard$k.jsonl"
        done
    done
    echo "$out"
}

# prepared_train + prepared_val run ~3.3 GB per generation at a window of one,
# and scale with the window — 10 generations x a 3-wide window would want
# ~100 GB against the ~91 GB free when this was written. They are fully
# regenerable from the shards, so drop the previous generation's once the
# current one has trained. The .prepared marker goes with them: leaving it
# behind would make a resume skip prepare and then die on missing dims dirs.
prune_prepared() {
    local pg
    pg="$RUN_DIR/$(printf 'gen%02d' "$1")"
    [ -d "$pg" ] || return 0
    [ -d "$pg/prepared_train" ] || [ -d "$pg/prepared_val" ] || return 0
    rm -rf "$pg/prepared_train" "$pg/prepared_val"
    rm -f "$pg/.prepared"
    log "pruned prepared_* from $(basename "$pg") (regenerable from its shards)"
}

# ---- nn sidecar lifecycle (plan 024 Stage 5) --------------------------------
# One server for the whole phase, torn down before the train phase so the
# trainer gets the whole card. A dead server is *not* fatal: the Rust client
# falls back to tract, so a shard gets slower but still finishes, which
# preserves the loop's existing "a dead shard is a warning" semantics.
NN_SERVER_PID=""
nn_server_start() {
    [ "$NN_SERVER" = "on" ] || return 0
    local model="$1"
    [ -f "${model%.onnx}.pt" ] || {
        status "WARN: no ${model%.onnx}.pt beside the champion — sidecar needs the trainer's own weights; running on tract"
        return 0
    }
    rm -f "$NN_SOCKET"
    "$PY" "$REPO/scripts/nn_server.py" --socket "$NN_SOCKET" --device cuda \
        --model "$model" --stats-every 300 >> "$RUN_DIR/nn_server.log" 2>&1 &
    NN_SERVER_PID=$!
    # Warm-up loads the net, traces it and captures 12 CUDA graphs; the
    # socket only appears once the batcher is ready, so waiting for the
    # socket is exactly the right readiness signal.
    local i=0
    while [ ! -S "$NN_SOCKET" ]; do
        i=$((i + 1))
        if [ "$i" -gt 120 ] || ! kill -0 "$NN_SERVER_PID" 2>/dev/null; then
            status "WARN: nn_server did not come up in ${i}s — see nn_server.log; shards will use tract"
            NN_SERVER_PID=""
            return 0
        fi
        sleep 1
    done
    status "nn_server up (pid $NN_SERVER_PID, $(basename "$model"), socket $NN_SOCKET)"
}
nn_server_stop() {
    [ -n "$NN_SERVER_PID" ] || return 0
    kill "$NN_SERVER_PID" 2>/dev/null
    wait "$NN_SERVER_PID" 2>/dev/null
    status "nn_server stopped (pid $NN_SERVER_PID)"
    NN_SERVER_PID=""
    rm -f "$NN_SOCKET"
}
# ---- hub + local worker lifecycle (plan 041) --------------------------------
# The hub is idempotent to start: if one already answers on $HUB_PORT (a
# previous loop instance, or started by hand so remote workers could join
# early) it is reused and left running on exit.
HUB_PID=""
WORKER_PID=""
hub_start() {
    if "$HUB" status --hub "$HUB_URL" --token-file "$HUB_TOKEN_FILE" > /dev/null 2>&1; then
        log "hub already running on $HUB_URL; reusing"
        return 0
    fi
    "$HUB" serve --bind "0.0.0.0:$HUB_PORT" --token-file "$HUB_TOKEN_FILE" >> "$RUN_DIR/hub.log" 2>&1 &
    HUB_PID=$!
    local i=0
    until "$HUB" status --hub "$HUB_URL" --token-file "$HUB_TOKEN_FILE" > /dev/null 2>&1; do
        i=$((i + 1))
        if [ "$i" -gt 30 ] || ! kill -0 "$HUB_PID" 2>/dev/null; then
            die "hub did not come up on $HUB_URL in ${i}s — see hub.log"
        fi
        sleep 1
    done
    status "hub up (pid $HUB_PID, port $HUB_PORT, token $HUB_TOKEN_FILE)"
}
hub_stop() {
    [ -n "$HUB_PID" ] || return 0
    kill "$HUB_PID" 2>/dev/null
    wait "$HUB_PID" 2>/dev/null
    HUB_PID=""
}
# $1 = parallel games, $2 = log file (per phase, so a fallback warning is
# attributable); the sidecar socket is passed when the server is up.
worker_start() {
    local extra=""
    [ -n "$NN_SERVER_PID" ] && extra="--nn-server $NN_SOCKET"
    # shellcheck disable=SC2086
    "$WORKER" --hub "ws://127.0.0.1:$HUB_PORT/ws" --token-file "$HUB_TOKEN_FILE" \
        --name "local" --parallel-games "$1" --cache-dir "$WORKER_CACHE" $extra \
        >> "$2" 2>&1 &
    WORKER_PID=$!
    log "local worker started (pid $WORKER_PID, x$1${extra:+ via sidecar})"
}
worker_stop() {
    [ -n "$WORKER_PID" ] || return 0
    kill "$WORKER_PID" 2>/dev/null
    wait "$WORKER_PID" 2>/dev/null
    WORKER_PID=""
}
cleanup() { worker_stop; nn_server_stop; hub_stop; }

